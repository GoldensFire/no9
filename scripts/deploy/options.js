// Ключи выкладки и пути к тому, что она перекладывает.
//
// Разбираются один раз при загрузке и дальше только читаются. Отдельно потому,
// что спрашивают их все три половины выкладки сразу: запуск wrangler смотрит
// на --local, заливка — на --full, а полка — на --no-state.

import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Два шага вверх, а не один: файл лежит в scripts/deploy/, и корень проекта
// от него через папку. Считается он здесь одним местом — все остальные куски
// выкладки берут его отсюда и сами до него не дотягиваются
export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const dataPath = path.join(root, 'cf', 'data');

/**
 * Склад готовых уменьшенных обложек. Он же `config.thumbsPath` дома и он же
 * `thumbsPath` у полки (см. scripts/state/config.js) — папка одна на всех,
 * а считается здесь заново нарочно: выкладка запускается и в GitHub Actions,
 * где src/config.js с его ключами и настройками не нужен вовсе (та же причина,
 * по которой ключи Cloudflare читает scripts/deploy/wrangler.js, а не config).
 *
 * Отсюда его берёт scripts/deploy-logos.js: всё, что лежит в этой папке,
 * и есть то, что видно на сайте.
 */
export const thumbsPath = path.join(root, 'data', 'thumbs');

/**
 * Склад крупных копий — тех, что уезжают в чужое окно карточкой ссылки.
 * Считается здесь по той же причине и берётся тем же scripts/deploy-logos.js:
 * обе копии теперь едут наверх одним Worker'ом и одной командой.
 *
 * До этого крупные копии возила статика главного Worker'а, то есть только
 * домашняя выкладка, — и у пака, найденного обходом между двумя выкладками,
 * картинки в Discord не было вовсе (пак 21599, сентябрь 2026).
 */
export const previewsPath = path.join(root, 'data', 'previews');

export const local = process.argv.includes('--local');

/**
 * Выкладывать ли только базу, не трогая сам сайт.
 *
 * В Actions — всегда, и это не ключ запуска, а свойство места. В репозитории
 * лежит ровно та половина проекта, которой живёт обновление базы: обход ВК,
 * разбор паков, статистика, разметка Gemini, заливка в D1 и полка. Сайта там
 * нет — ни web/, ни cf/src/, ни src/meta/, — и собирать статику из того, чего
 * нет, ночь не может и не должна.
 *
 * Что из этого следует. Данные наверху обновляются каждую ночь, как и раньше:
 * новые паки, новая статистика, новые уровни сложности. А всё, что считается
 * при сборке и лежит статикой, — счётчики по темам в prebuilt.json, список слов
 * для поиска, список авторов — обновляется дома, обычным `npm run deploy`.
 * Там же посылается и пинг IndexNow: ему нужны и web/, и карта сайта.
 */
export const dbOnly = process.argv.includes('--db-only') || !!process.env.GITHUB_ACTIONS;

/**
 * Класть ли базу на полку после удачной заливки. По умолчанию — да, и это
 * не мелочь, а вторая половина сверки (см. scripts/state.js): здешний запуск
 * сайта подгоняет базу под полку, значит на полке обязано лежать ровно то,
 * что стоит на сайте. Не положить сюда — и следующий запуск дома вернёт
 * вчерашнюю копию, стерев то, что только что уехало наверх.
 *
 * Ключ --no-state снимает это для разовых случаев. В GitHub Actions полка
 * и так обновляется отдельным шагом (.github/workflows/nightly.yml) — второй
 * раз гнать туда семьдесят мегабайт незачем.
 */
export const toShelf = !local && !process.argv.includes('--no-state') && !process.env.GITHUB_ACTIONS;

/**
 * Местная копия — всегда целиком и без отметки «доехало». Она живёт в .wrangler
 * рядом с проектом и к настоящей базе в Cloudflare отношения не имеет: запомнить
 * по ней, что там уже лежит, значило бы соврать самим себе, и следующая настоящая
 * выкладка недосчиталась бы всего, что проверялось на местной.
 */
export const whole = local || process.argv.includes('--full');

export const DB_NAME = 'firepacks';
