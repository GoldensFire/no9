// Досыл недостающих колонок в таблицы посетителей.
//
// ————— зачем это нужно —————
//
// cf/schema.sql заводит таблицы через CREATE TABLE IF NOT EXISTS: он прогоняется
// перед каждой выкладкой и со второго раза обязан не делать ничего. Обратная
// сторона у этого одна и известная: таблице, которая уже существует, новая
// колонка из этого файла не достанется никогда — «IF NOT EXISTS» видит таблицу
// и уходит, не заглядывая внутрь.
//
// Дописать колонку можно только ALTER'ом, а «ADD COLUMN IF NOT EXISTS» SQLite
// не знает: второй прогон такого запроса — отказ, то есть сорванная выкладка.
// Поэтому здесь сперва спрашивается, чего в таблице не хватает, и дописывается
// только оно.
//
// Дома то же самое и тем же способом делает src/db.js (см. ALTER TABLE packages
// там же) — разница только в том, что дома база под рукой, а сюда приходится
// спрашивать через сеть.
//
// ————— почему это шаг выкладки, а не отдельная команда —————
//
// Отдельной командой сделана перестройка таблицы входов (npm run cf:migrate-auth):
// она сносит и собирает заново таблицу, к которой привязано всё, что накопили
// посетители, и делать такое каждую ночь незачем. Досыл колонки — работа другого
// рода: она ничего не сносит, ничего не переписывает и со второго раза не делает
// ничего.
//
// А ходить она должна сама вот почему. Worker выкладывается тем же запуском,
// что и схема, и новый его код спрашивает у базы новую колонку с первого же
// запроса. Забыли прогнать досыл руками — и сайт отвечает «no such column»
// не в тот момент, когда об этом можно узнать, а всем посетителям сразу.
//
// ————— и почему он идёт ПЕРЕД схемой —————
//
// Потому что на новую колонку в схеме стоит указатель, а «CREATE INDEX …
// (parent_id, …)» по колонке, которой в таблице нет, — это не тихая осечка,
// а отказ базы и сорванная посреди работы выкладка. Схема вправе рассчитывать,
// что все колонки уже на месте; обеспечить это — здешнее дело.
//
// Пустой базе такой порядок не мешает ничем: таблицы там ещё нет вовсе,
// досылать нечего, и заводит её следом схема — сразу нужного вида, вместе
// с колонкой и указателем.

import { askRows } from './d1.js';

/**
 * Что должно быть в таблицах помимо того, с чем их когда-то завели.
 *
 * Колонка называется вместе со своим определением — тем же самым, что стоит
 * в cf/schema.sql. Разойтись им нельзя: чистая база получает колонку оттуда,
 * а живущая — отсюда, и это обязана быть одна и та же колонка.
 *
 * Только необязательные (без NOT NULL без умолчания): SQLite дописывает колонку
 * в существующие строки тем, что в определении, и обязательной колонке
 * без умолчания взяться в старой строке неоткуда.
 */
const COLUMNS = [
	// На чей комментарий это ответ. Разговор под паком был плоским, ветки
	// в нём появились вместе с этой колонкой (см. cf/src/library/comments.js).
	['comments', 'parent_id', 'INTEGER'],
];

/**
 * Дописать недостающее. Ходит в базу один раз на таблицу — за её же собственным
 * описанием: sqlite_master отдаёт текст CREATE TABLE, и колонка в нём или есть,
 * или нет.
 *
 * Отдельного указателя это не касается: указатели заводятся через
 * CREATE INDEX IF NOT EXISTS и доезжают до живущей базы сами, схемой.
 */
export async function addMissingColumns() {
	const tables = [...new Set(COLUMNS.map(([table]) => table))];
	const known = new Map();

	for (const table of tables) {
		const [row] = await askRows(
			`SELECT sql FROM sqlite_master WHERE type = 'table' AND name = '${table}'`,
		);

		known.set(table, row?.sql ?? null);
	}

	let added = 0;

	for (const [table, name, definition] of COLUMNS) {
		const sql = known.get(table);

		// Таблицы нет вовсе — значит, база пустая, и заведёт её следом схема,
		// уже с этой колонкой. Дописывать нечего
		if (!sql) {
			continue;
		}

		// Границы слова, чтобы «parent_id» не нашёлся внутри «grandparent_id»
		if (new RegExp(`\\b${name}\\b`).test(sql)) {
			continue;
		}

		console.log(`Дописываем ${table}.${name}: этой колонки в базе ещё нет.`);
		await askRows(`ALTER TABLE ${table} ADD COLUMN ${name} ${definition}`);
		added += 1;
	}

	// Без «все колонки на месте»: на пустой базе их нет вовсе, там нет и таблиц,
	// и сказать так значило бы соврать ровно в том случае, ради которого сюда
	// и заглядывают в первый раз
	console.log(added > 0 ? `Дописано колонок: ${added}.` : 'Дописывать нечего.');
}
