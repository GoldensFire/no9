// Технические работы: зажечь плашку на сайте, погасить её и убедиться, что
// после выкладки сайт отвечает.
//
// Отдельным файлом от заливки потому, что занятие тут другое: та перекладывает
// базу, а это — разговор с посетителем, которого выкладка застала на сайте.
// Одна строка в базе (site_state, см. cf/schema.sql), одна полоса наверху
// страницы (см. web/maintenance.js) и одна проверка живости — больше здесь
// ничего нет.
//
// ————— почему выкладка вообще заметна снаружи —————
//
// Сайт при ней не падает. Worker подменяется целиком и атомарно: запрос
// достаётся либо старой версии, либо новой, и «между» не бывает. Статика уезжает
// с отпечатком содержимого в имени, то есть новые файлы не затирают старых,
// и страница, открытая до выкладки, договаривает своими. База льётся построчно
// обычными запросами, а не «импортом», который блокирует её целиком
// (см. пояснение в scripts/deploy/d1.js).
//
// Заметна другая вещь: те пять-десять минут, что идёт заливка, база наполовину
// старая и наполовину новая. Пак открылся, а обложки у него ещё нет; в выдаче
// семь тысяч паков вместо одиннадцати; счётчик по теме разошёлся со списком.
// Всё это выглядит поломкой — и человек уходит с мыслью, что сайт сломан,
// вместо того чтобы вернуться через десять минут. Плашка говорит ему то, что
// есть на самом деле.

import fs from 'node:fs';
import path from 'node:path';

import { askDatabase } from './d1.js';
import { dataPath } from './options.js';
import { siteOrigin } from './site.js';
import { CLOUDFLARE_ENV, sleep } from './wrangler.js';

/**
 * Сломает ли нынешняя заливка сайт на время работ — то есть звать ли плашку.
 *
 * Ломает только полная: она начинается со сноса таблиц (DROP TABLE, см.
 * scripts/export-d1.js), и до конца заливки в выдаче половина паков. Обычная же
 * ночная или ежечасная заливка досылает изменившиеся строки поверх живых —
 * каждый пак меняется одной вставкой, и посетитель ничего не замечает. Плашка
 * при ней горела каждую ночь и рассказывала о работах, которых для человека
 * не было (ноябрь 2026, владелец попросил так не делать).
 *
 * Снос, если он есть, стоит в самом начале первого файла — дальше читать незачем.
 */
export function pourBreaksSite() {
	try {
		const first = fs.readdirSync(dataPath).filter(name => name.endsWith('.sql')).sort()[0];

		if (!first) {
			return false;
		}

		const file = fs.openSync(path.join(dataPath, first), 'r');
		const head = Buffer.alloc(64 * 1024);
		const size = fs.readSync(file, head, 0, head.length, 0);
		fs.closeSync(file);

		return /DROP TABLE/i.test(head.toString('utf8', 0, size));
	} catch {
		// Не прочиталось — пусть лучше лишняя плашка, чем молчаливая поломка
		return true;
	}
}

/**
 * Можно ли вообще писать в базу наверху отсюда.
 *
 * Постоянного ключа может и не быть: выкладка руками после `wrangler login`
 * — обычное дело, и заливка в этом случае идёт по-старому, файлом
 * (см. pour в scripts/deploy/d1.js). REST пропуском из браузера не пользуется,
 * а спрашивать учётную запись без ключа значит уронить всю выкладку на попытке
 * зажечь плашку — то есть на самом необязательном её шаге.
 */
const canWrite = () => Boolean(CLOUDFLARE_ENV.CLOUDFLARE_API_TOKEN);

/** Как называется строка. То же имя читает cf/src/library/status.js. */
const KEY = 'maintenance';

/**
 * Сколько плашка держится сама по себе, миллисекунды.
 *
 * Гасит её выкладка, когда закончила. Но выкладка может и не закончиться:
 * оборвалась сеть, отказала база, человек закрыл окно на середине. Строка
 * в базе после этого осталась бы гореть навсегда — и сайт до следующей
 * выкладки рассказывал бы о работах, которых нет.
 *
 * Поэтому у неё стоит срок. Сорок минут — это вчетверо больше самой долгой
 * выкладки из всех, что бывали, и вдесятеро меньше того времени, за которое
 * кто-нибудь заметит забытую плашку.
 */
const WORKS_TTL = 40 * 60 * 1000;

/**
 * Зажечь плашку.
 *
 * Отказ не валит выкладку и даже не считается за неудачу: плашка — вежливость,
 * а не часть переливки базы. Не записалась (нет ключа REST, не доехала схема,
 * не ответила база) — говорим об этом строкой в журнале и льём дальше.
 *
 * @param {string} note что написать людям; пусто — текст по умолчанию
 *   из web/maintenance.js
 */
export async function worksOn(note = '') {
	if (!canWrite()) {
		console.log('Постоянного ключа Cloudflare нет — плашку работ ставить нечем.');
		return;
	}

	const state = {
		on: true,
		note,
		since: Date.now(),
		until: Date.now() + WORKS_TTL,
	};

	const complaint = await write(state);

	console.log(complaint
		? `Плашку работ поставить не вышло (${complaint}) — выкладываем молча.`
		: 'Плашка технических работ зажжена: сайт предупреждает посетителей.');
}

/**
 * Погасить плашку.
 *
 * Строка не удаляется, а гасится: так в базе остаётся видно, когда работы были
 * в последний раз, — а это первое, что спрашивают, когда сайт «странно себя вёл
 * вчера вечером».
 */
export async function worksOff() {
	if (!canWrite()) {
		return;
	}

	const complaint = await write({ on: false, note: '', since: 0, until: 0 });

	console.log(complaint
		? `Плашку работ погасить не вышло (${complaint}). Погаснет сама, не позже чем через сорок минут.`
		: 'Плашка технических работ погашена.');
}

/** Записать состояние. Возвращает жалобу строкой или null. */
function write(state) {
	const value = JSON.stringify(state).replace(/'/g, "''");

	return askDatabase(
		'INSERT OR REPLACE INTO site_state (key, value, updated_at) '
		+ `VALUES ('${KEY}', '${value}', ${Date.now()})`,
	);
}

/** Сколько раз спросить сайт после выкладки и сколько ждать между попытками, с. */
const HEALTH_TRIES = [2, 3, 5, 10, 15];

/**
 * Проверка живости: отвечает ли выложенный сайт.
 *
 * Спрашиваются две вещи, и обе нарочно. Главная страница — это Worker вместе
 * со статикой: она собирается из вёрстки, в которую он кладёт первую страницу
 * выдачи. А /api/facets — это Worker вместе с базой: не ответит он только тогда,
 * когда с базой что-то не так. Одной страницы мало: она открывается и с мёртвой
 * базой, потому что готовые ответы лежат файлом статики (см. cf/src/prebuilt.js).
 *
 * Первый запрос после выкладки нередко приходит в ещё не поднявшийся Worker,
 * поэтому попыток несколько и с растущим ожиданием. Не ответил и после всех —
 * говорим громко и НЕ гасим плашку: пока сайт не отвечает, посетителю лучше
 * видеть «идут работы», чем пустой экран без объяснений.
 *
 * @returns {Promise<boolean>} ожил ли сайт
 */
export async function siteHealthy() {
	const origin = await siteOrigin();

	if (!origin) {
		console.log('Адрес сайта не спросился — проверять живость нечем.');
		return true;
	}

	for (let attempt = 0; attempt <= HEALTH_TRIES.length; attempt += 1) {
		const complaint = await knock(origin);

		if (!complaint) {
			console.log(`Сайт отвечает: ${origin}`);
			return true;
		}

		if (attempt === HEALTH_TRIES.length) {
			console.error('');
			console.error(`Сайт не ответил после выкладки: ${complaint}`);
			console.error('Плашка технических работ оставлена гореть — она погаснет сама');
			console.error('через сорок минут. Посмотрите журнал Worker: npx wrangler tail');
			return false;
		}

		const wait = HEALTH_TRIES[attempt];
		console.log(`Сайт ещё не отвечает (${complaint}) — ждём ${wait} с и пробуем снова.`);
		sleep(wait);
	}

	return false;
}

/** Один заход на сайт. Возвращает жалобу строкой или null. */
async function knock(origin) {
	for (const path of ['/', '/api/facets']) {
		let response;

		try {
			response = await fetch(`${origin}${path}`, {
				headers: { 'Cache-Control': 'no-cache' },
			});
		} catch (error) {
			return `${path}: ${error.message}`;
		}

		if (!response.ok) {
			return `${path}: HTTP ${response.status}`;
		}
	}

	return null;
}
