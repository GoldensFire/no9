// Выкладка сайта на Cloudflare одной командой.
//
// По порядку: собрать статику, выгрузить базу, залить схему (она создаётся
// только в первый раз), зажечь плашку работ, отправить обложки, залить паки,
// выложить Worker, убедиться, что он отвечает, погасить плашку, положить базу
// на полку и стукнуться в IndexNow. Всё это можно делать и вручную — здесь
// просто перечислено, что за чем, чтобы не забыть половину.
//
// Обложки стоят перед паками, а не после: наверху картинка обязана появиться
// не позже строки, которая на неё ссылается. Едут они не сюда, а своим
// Worker'ом без кода (см. scripts/deploy-logos.js) — тем и живут ночные
// выкладки из Actions, где статики главного сайта нет вовсе.
//
// Сайт при этом с ног не падает ни на миг, и это не случайность, а три вещи
// вместе: Worker подменяется атомарно, статика уезжает с отпечатком в имени
// (старые файлы никуда не деваются, и открытая страница договаривает своими),
// а база льётся построчно, а не блокирующим импортом. Что снаружи всё-таки
// заметно — так это несколько минут, пока база наполовину старая, — и про них
// сайт говорит плашкой (см. scripts/deploy/works.js).
//
// Ключи: --local  — залить в местную базу для проверки (npm run cf:dev),
//                   Worker при этом не выкладывается;
//        --db-only — только база, без выкладки Worker;
//        --full    — залить базу целиком, а не только изменившееся.
//
// Наверх обычно уезжают только те строки, которые с прошлого раза изменились
// (см. scripts/export-d1.js). Отметка «доехало» ставится здесь и только после
// того, как последний кусок SQL действительно выполнился: сорвавшаяся на середине
// выкладка не должна оставить базу в уверенности, что наверху лежит то, чего
// там нет. Следующий запуск тогда просто отправит те же строки заново.
//
// ————— Из чего она собрана —————
//
// Сам этот файл — только порядок шагов. Всё остальное рядом, в scripts/deploy/:
//
//   options.js    ключи выкладки и пути
//   wrangler.js   запуск wrangler: ключи Cloudflare, разбор отказов, execute
//   d1.js         заливка базы запросами через D1 REST, а не файлом
//   drift.js      сверка: не разошлось ли лежащее наверху с тем, что база
//                 считает отправленным
//   rowhash.js    отпечаток строки — один на выгрузку и на сверку
//   site.js       по какому адресу сайт открывается наверху
//   works.js      плашка «идут работы» и проверка живости после выкладки
//   indexnow.js   пинг поисковикам о том, что изменилось

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

import { dataPath, dbOnly, local, root, toShelf, whole } from './deploy/options.js';
import { checkAuth, run, writeDevVars } from './deploy/wrangler.js';
import { pour } from './deploy/d1.js';
import { addMissingColumns } from './deploy/columns.js';
import { forgetDrifted } from './deploy/drift.js';
import { pingIndexNow } from './deploy/indexnow.js';
import { siteHealthy, worksOff, worksOn } from './deploy/works.js';

/**
 * Положить базу на полку — ту самую, с которой её берёт запуск сайта дома
 * и ночной обход в облаке.
 *
 * Сорвалось — говорим и живём дальше: сайт-то уже обновлён, и валить из-за
 * этого всю выкладку не за что. Но сказать надо громко: пока на полке лежит
 * прежнее, здешняя база расходится с сайтом, и первая же сверка вернёт её
 * к вчерашнему виду.
 */
function shelve() {
	console.log('\n───── Полка ─────');

	const result = spawnSync(process.execPath, ['--no-warnings', 'scripts/state.js', 'push'], {
		cwd: root,
		stdio: 'inherit',
	});

	if (result.status !== 0) {
		console.error('');
		console.error('На полку база не легла. Сайт при этом обновлён — расходится только полка.');
		console.error('Положить руками: npm run state:push.');
		console.error('');
		console.error('Не откладывайте: пока на полке лежит прежнее, здешняя разметка живёт');
		console.error('только здесь, и ближайшая сверка при запуске сайта уведёт её в sibase.prev.db.');
	}
}

/**
 * Отправить наверх обложки — отдельным Worker'ом без кода
 * (см. scripts/deploy-logos.js).
 *
 * Стоит это до заливки паков нарочно: наверху строка пака и его картинка
 * появляются в таком порядке, что второе не отстаёт от первого. Наоборот
 * было бы ровно то, из-за чего всё и затевалось.
 *
 * Сорвалось — говорим и льём базу дальше. Обложки без свежих данных никому
 * не нужны, а свежие данные без обложек — половина дела, но половина сделанная;
 * ронять из-за картинок весь ночной обход не за что.
 */
function logos() {
	console.log('\n───── Обложки ─────');

	// Ключ передаётся руками, и это не мелочь: дочерний запуск свой argv видит
	// пустым и про --local не узнал бы ниоткуда. Без этой строки местная проверка
	// (npm run cf:dev) отправляла бы обложки в настоящий Cloudflare — что она
	// однажды и сделала.
	const keys = local ? ['--into-site'] : [];
	const failure = run('node', ['--no-warnings', 'scripts/deploy-logos.js', ...keys], { soft: true });

	if (!failure) {
		return;
	}

	console.error('');
	console.error('Обложки своим Worker\'ом наверх не уехали. База при этом зальётся');
	console.error('как обычно: ронять из-за картинок весь обход не за что.');
	console.error('Повторить отдельно: npm run deploy:logos');

	// Запасной ход — и только здесь, дома. Главный Worker сейчас поедет наверх,
	// и своей статикой он обложки увезти может: cf/public у него уже собрана.
	// Это ровно то, как обложки ездили раньше, — не лучше и не хуже, просто
	// не из Actions. В Actions (dbOnly) этого хода нет: там главный Worker
	// не выкладывается вовсе, и класть картинки некуда.
	if (dbOnly) {
		console.error('');
		console.error('До ближайшей выкладки из дома у паков, разобранных с прошлого раза,');
		console.error('будет квадрат с первой буквой названия вместо обложки.');
		return;
	}

	console.error('');
	console.error('Кладём их в статику главного Worker\'а — он сейчас поедет наверх и увезёт');
	console.error('их с собой, как возил до появления отдельного Worker\'а обложек.');

	run('node', ['--no-warnings', 'scripts/deploy-logos.js', '--into-site'], { soft: true });
}

async function main() {
	if (!local) {
		const config = fs.readFileSync(path.join(root, 'wrangler.jsonc'), 'utf8');

		if (config.includes('поставит-npm-run-cf-setup')) {
			console.error('Сначала заведите базу в Cloudflare: npm run cf:setup');
			process.exit(1);
		}

	}

	// Первым делом, до всякой долгой работы: без пропуска наверх всё равно
	// ничего не уедет, а узнать об этом лучше сейчас, чем через пять минут
	checkAuth();

	// Статику собирает тот, у кого она есть. В репозитории её нет: наверх
	// из Actions уезжает только база, а сайт — код страниц, стили и готовые
	// ответы prebuilt.json — выкладывается из дома (см. dbOnly в deploy/options.js).
	// Поэтому «только база» здесь не «собери и не выкладывай», а «не собирай»:
	// scripts/build-web.js читает web/ и src/meta/, которых в Actions попросту нет.
	if (dbOnly) {
		console.log('\nСтатику не собираем: наверх едет только база.');
	} else {
		console.log('\n───── Статика ─────');
		run('node', ['--no-warnings', 'scripts/build-web.js']);
	}

	// До выгрузки, а не после: сверка убирает отметки «отправлено» у строк,
	// которые наверху выглядят иначе, чем база про них думает, — и выгрузка
	// следом отправляет их как изменившиеся. Порядок тут и есть весь смысл
	// (см. scripts/deploy/drift.js).
	console.log('\n───── Сверка с базой наверху ─────');
	await forgetDrifted();

	console.log('\n───── Выгрузка базы ─────');
	run('node', ['--no-warnings', 'scripts/export-d1.js', ...(whole ? ['--full'] : [])]);

	// Схема прогоняется каждый раз, но делает что-то только в первый: таблицы
	// с оценками и входами создаются с IF NOT EXISTS и потом не трогаются.
	// Заливка паков их не касается вовсе — иначе выкладка стирала бы всё,
	// что накопили посетители (см. cf/schema.sql).
	console.log('\n───── Таблицы посетителей ─────');

	// Сперва — то, чего схема живущей базе донести не может: у таблицы, которая
	// уже есть, «CREATE TABLE IF NOT EXISTS» новых колонок не заводит
	// (см. scripts/deploy/columns.js).
	//
	// Порядок здесь не вкусовщина. В схеме на новую колонку стоит указатель,
	// а указатель по колонке, которой в таблице нет, — это отказ и сорванная
	// выкладка: «no such column: parent_id». Схема, стало быть, вправе
	// рассчитывать, что колонки уже на месте, — и досыл обязан идти до неё,
	// а не после. Пустой базе это ничем не мешает: таблицы там ещё нет вовсе,
	// досылать нечего, и заводит её следом схема — сразу нужного вида.
	await addMissingColumns();

	await pour('cf/schema.sql');

	// Плашку зажигаем только теперь, а не первым делом: строка её ложится
	// в site_state, а таблицу эту создаёт схема, которую только что залили.
	// Ничего от этого не теряется — до сих пор шли выгрузка базы и сборка
	// статики, то есть работа дома, снаружи не видная вовсе. Заметное начинается
	// со следующей строки.
	if (!local) {
		console.log('\n───── Технические работы ─────');
		await worksOn();
	}

	logos();

	console.log('\n───── Паки ─────');

	for (const name of fs.readdirSync(dataPath).sort()) {
		await pour(path.join('cf', 'data', name));
	}

	// Заливка только что переписала строки паков теми, что лежат дома, — а дома
	// про снятые с публикации паки не знает никто. Возвращаем им запрет по списку,
	// который заливка не трогает (см. cf/hidden.sql).
	console.log('\n───── Снятые с публикации ─────');
	await pour('cf/hidden.sql');

	if (local) {
		writeDevVars();
		console.log('\nМестная копия готова. Дальше: npx wrangler dev');
		return;
	}

	// Всё доехало — можно запомнить, что именно
	run('node', ['--no-warnings', 'scripts/export-d1.js', '--commit']);

	if (dbOnly) {
		console.log('\nБаза залита. Сам сайт не трогали.');

		// Работы кончились ровно здесь: базу перелили, а сайт этой командой
		// и не трогали вовсе
		await worksOff();

		if (toShelf) {
			shelve();
		}

		return;
	}

	console.log('\n───── Выкладка ─────');
	run('npx', ['wrangler', 'deploy']);

	// Плашка гаснет не по факту «команда прошла», а по факту «сайт отвечает»:
	// выложенный Worker поднимается не мгновенно, и первые секунды после команды
	// сайт может ещё молчать. Не ответил совсем — плашка остаётся гореть
	// (см. siteHealthy в scripts/deploy/works.js): пустой экран без объяснений
	// хуже честного «идут работы».
	console.log('\n───── Проверка ─────');

	if (await siteHealthy()) {
		await worksOff();
	}

	// Сайт наверху обновлён — самое время сказать об этом поисковикам. До полки,
	// а не после: отметка «эти адреса отправлены» ложится в домашнюю базу,
	// и уехать на полку она должна вместе со всем остальным.
	await pingIndexNow();

	if (toShelf) {
		shelve();
	}

	console.log('\nГотово.');
}

await main();
