/**
 * Чем ежечасный обход отличается от забега за свежим внутри ночи.
 *
 * Работа у них одна и та же, а вот тема читается по-разному. Ночь читает
 * обсуждение целиком: только тот, кто дошёл до конца, вправе судить, что
 * в старом сообщении подменили или убрали файл (см. applyPending в индексаторе).
 * Стоит это десяти минут запросов к ВК на тему в двадцать шесть тысяч сообщений —
 * для ночи с её четырьмя часами это ничто.
 *
 * Ежечасному обходу те же десять минут — это весь его смысл: он ходит ради нуля
 * или одного нового пака, а тратил на дорогу столько же, сколько ночь. Поэтому
 * он читает только хвост темы (`--tail`) — сообщения не старше своей отсечки, —
 * и укладывается в секунды. Пропавших файлов он при этом не замечает, и это
 * не потеря: их заметит ночь.
 *
 * Отсечка эта считается не от часов, а от сделанного: обход начинает оттуда,
 * где кончил предыдущий такой же, сколько бы между ними ни прошло
 * (см. src/indexer/tail.js). Раньше она была «сутки назад плюс сутки запаса»,
 * и это работало ровно до тех пор, пока обход приходил каждый час, — а
 * расписание GitHub часть запусков пропускает вовсе. Пропуск длиннее двух суток
 * означал дыру, в которой выложенный пак ежечасному обходу уже не попадался
 * никогда: его подбирала только ночь.
 */
