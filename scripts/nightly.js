/**
 * Чем ночь размечает паки — всегда одним и тем же.
 *
 * Раньше здесь стоял ключ --fallback: кончились у модели суточные запросы —
 * перейди на соседнюю Flash-Lite и работай дальше. Считалось это выгодой:
 * лишняя тысяча размеченных паков за ночь вместо остановки на середине.
 *
 * Выгода вышла мнимой. Разметка — не работа «лишь бы сделать»: пак, размеченный
 * слабой моделью, придётся переспрашивать, и переспрашивать вручную, потому что
 * по базе не видно, где в ней ошибка. Ночь же выбирала модель не по тому, какая
 * лучше, а по тому, у какой к трём часам остались запросы, — и половина базы
 * размечалась моделью, которую никто для неё не выбирал. Хуже того, галочка
 * «переспросить размеченное моделью послабее» после этого показывала не то,
 * что ночью не хватило времени, а то, что ночью не хватило квоты.
 *
 * Поэтому модель у ночи одна и названа прямо здесь. Кончились у неё запросы —
 * ночь кончилась, а очередь никуда не денется: непеределанное сделает следующая.
 * Ключ --model перебивает выбранное на странице обновления, так что ночь
 * не зависит и от того, что там выбрали днём для разовой работы.
 */
const NIGHT_MODEL = '--model=gemini-3.5-flash-lite';

/**
 * ...а у ежечасного обхода — не одна, и это не отмена сказанного выше,
 * а другая задача.
 *
 * Всё рассуждение про «разметка вперемешку хуже, чем разметка не сегодня»
 * держится на числах ночи: там очередь на тысячи паков, переключение решает,
 * чем размечена ПОЛОВИНА БАЗЫ, и выбирается модель не по качеству, а по тому,
 * у какой к трём часам остались запросы.
 *
 * У ежечасного обхода очередь — один пак. Тот, что появился в обсуждении час
 * назад. Упереться в лимит он может ровно одним способом: ночь перед этим
 * выбрала суточную квоту до дна, — и тогда выбор у него не «эта модель или
 * та», а «сильнейшая из живых или никакая». Никакая означает карточку без типа,
 * без описания, без сложности и без обложки, висящую серой строкой до следующей
 * ночи; и это, в отличие от ночного случая, не «сделаем завтра», а прямая
 * потеря — доделывать её придётся тем же самым запросом, только сутки спустя.
 *
 * Поэтому здесь переход разрешён, и разрешён по всем моделям подряд, начиная
 * с самой мощной: двадцати суточных запросов старшего Flash хватает на двадцать
 * таких паков, то есть на сутки с лихвой (см. --fallback=any
 * в src/indexer/options.js и nextSpareModel в src/models.js).
 */
const HOUR_FALLBACK = '--fallback=any';

/**
 * Сколько всего минут отпущено ночи — вместе с выкладкой.
 *
 * Число это не про экономию, а про то, чтобы работа доехала до сайта. Очередь
 * разметки бесконечна: паков в базе тысячи, за ночь размечаются сотни, и обход
 * сам собой не кончается никогда — он кончается тем, что его убивают. В облаке
 * убивает GitHub на шести часах, и убивает грубо: работа обрывается посреди
 * запроса, а всё, что стоит после неё, — выкладка, отчёт — не выполняется вовсе.
 * Так прошли две ночи подряд, 16 и 17 августа 2026: по пять с лишним часов
 * разметки, около двух тысяч размеченных паков, и ни одного на сайте.
 *
 * Поэтому ночь знает свой срок сама и уходит с запасом: индексатору отдаётся
 * время до срока минус запас на выкладку, и он сворачивает очередь по часам
 * (см. --minutes в src/indexer/options.js). Заканчивается всё как обычно — сборкой,
 * выкладкой и отчётом, только сделано за ночь меньше. Меньше, зато на сайте.
 *
 * Четыре часа — не круглое число, а мерка по живой ночи: пять часов разметки
 * шли в один и тот же предел суточных запросов Gemini, то есть последний час
 * упирался уже не в работу, а в ожидание квоты.
 */
const BUDGET_DEFAULT = 240;
const budget = Number(process.argv.find(arg => arg.startsWith('--minutes='))?.split('=')[1]) || BUDGET_DEFAULT;

/**
 * Сколько минут оставить выкладке и возврату базы на полку.
 *
 * Выкладка — это заливка изменившихся строк в D1 и обложек в R2; на живой базе
 * она укладывается в считаные минуты, но зависит от чужой стороны, и запас
 * нужен именно на её медленный день.
 */
const DEPLOY_RESERVE = 20;

/**
 * «Только свежее»: сделать первый проход и на нём закончить, не трогая
 * остальную базу.
 *
 * Ради ежечасного обхода (.github/workflows/hourly.yml). Пак, выложенный
 * в обсуждение в полдень, до этого ждал сайта до полуночи — не потому, что
 * работы с ним много (её минуты), а потому, что делалась она заодно с полным
 * проходом по одиннадцати тысячам паков. Теперь новое подбирается каждый час
 * тем же самым забегом за свежим, а ночь по-прежнему занимается всей базой.
 */
const onlyFresh = process.argv.includes('--only-fresh');

/** Свои ключи; остальные — не наше дело, они для индексатора. */
const OWN_FLAGS = ['--no-deploy', '--no-fresh', '--only-fresh'];
const indexerArgs = process.argv.slice(2)
