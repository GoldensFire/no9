import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Два шага вверх, а не один: файл лежит в scripts/state/, и корень проекта
// от него через папку. Считается он здесь одним местом — остальные куски
// берут его отсюда и сами до него не дотягиваются
export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Отметка релиза, к которой прикладывается состояние. Одна на всё время. */
