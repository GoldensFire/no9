/**
 * Секреты в этот файл не пишутся: сначала смотрим переменную окружения,
 * потом файл в папке data. Файл удобнее — положил один раз и забыл.
 */
function readSecret(envName, fileName) {
	if (process.env[envName]) {
		return process.env[envName].trim();
	}

	try {
		return fs.readFileSync(path.join(root, 'data', fileName), 'utf8').trim();
	} catch {
		return '';
	}
}

