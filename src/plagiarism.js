// Кто у кого списал. Отпечатки вопросов, поиск донора и приговор паку.
//
// Отдельным модулем — по той же причине, что topics.js и franchise.js: здесь
// одна арифметика и ни одного похода ни в базу, ни в сеть. На вход подаются
// строки паков как они лежат в packages вместе с их отпечатками, на выход —
// приговоры; читает базу и пишет в неё шаг plagiarism в src/indexer/plagiarism.js.
//
// ————— что вообще сравнивается —————
//
// Вопрос целиком: его текст, имена приложенных к нему файлов и правильный
// ответ (см. questionParts в src/siq.js). Совпало всё трое — это тот же самый
// вопрос, и никакого другого объяснения у такого совпадения нет.
//
// Кроме одного: имя файла — не файл. Медиавопрос текста не имеет вовсе, и от
// него остаются имя да ответ; а имена у медиафайлов сплошь и рядом безликие —
// «01.mp3», «Опенинг.mp3», «1.jpg». Ответ же у вопроса «назовите аниме»
// задаёт не пак, а само произведение. Двое, независимо взявшие один и тот же
// опенинг, получают одинаковую пару — и невиновны. Поэтому у совпавших
// вопросов сверяется ещё и вес приложенных файлов: разошёлся вес — файлы
// разные, и это не заимствование (см. sameWeight). Вес берётся из оглавления
// архива, то есть достаётся даром: разбор его и так читает.
//
// И по той же причине одного имени файла мало. Вопрос, у которого нет ни
// текста, ни ответа, — это голое «01.mp3», и совпадение таких вопросов не
// говорит ровно ничего: одинаково названных файлов в паках тысячи, а сказать
// про них, тот ли это файл, нечем — вес отменяет находку, но сам находкой
// не бывает. Медиавопрос идёт в счёт тогда, когда сошлись и имя файла,
// и ответ; без ответа он остаётся немым (см. MUTE) — он есть, он считается
// вопросом темы, но ни донором, ни уликой не становится.
//
// Раньше сравнивались темы — их название вместе с огрызком содержимого (полем
// sample), — и мерка эта была не по задаче. Название темы у разных людей
// совпадает сплошь и рядом: «Фильмы», «Кино», «Аниме», «Разное» стоят
// в сотнях паков, и ничьей собственностью не являются. Собственность — это
// то, что внутри темы: сами вопросы. Пусть у двух паков хоть все темы названы
// одинаково — если вопросы в них разные, ни один ни у кого не списывал;
// а вот десяток дословно одинаковых вопросов при разных названиях тем — это
// ровно то, что искали.
//
// ————— почему сравниваются числа, а не строки —————
//
// Вопросов в базе больше миллиона, и сравнивать их попарно — это часы.
// Сравнивается восьмибайтное число: первые восемь байт SHA-1 от склейки
// приведённых к общему виду текста, имён файлов и ответа. Восьми байт хватает
// с запасом — на полутора миллионах отпечатков вероятность случайного
// совпадения двух разных примерно пять стомиллионных долей процента, то есть
// на несколько порядков реже, чем вероятность, что два человека независимо
// написали дословно один и тот же вопрос с тем же ответом.
//
// Текста вопросов в базе при этом нет вовсе, и это не экономия ради экономии:
// разбор их читает и выбрасывает (см. src/siq.js), потому что весят они больше
// всего остального пака вместе взятого. Отпечаток — двенадцать байт на вопрос
// вместе с его местом в раундах, то есть тринадцать мегабайт на всю библиотеку.
//
// ————— почему приговор всё-таки про темы —————
//
// Считается всё по вопросам, а метка «взято отсюда» ставится теме: мельче темы
// сайт ничего не показывает (см. roundsForApi в src/keys.js). Метку получает
// всякая тема, где нашёлся хоть один чужой вопрос, — но вместе с меткой едет
// и число этих вопросов, и по нему карточка отличает тему, списанную целиком,
// от темы, где чужих вопросов два из семи: первая красится уликой, вторая —
// приглушённым оранжевым, и подсказка у обеих называет и донора, и число.
//
// Раньше порог был в половину темы, и ниже него сайт молчал вовсе. Молчание
// это врало в другую сторону: пак, из которого по вопросу растащили тридцать
// тем, выглядел чистым — притом что за столом на этих вопросах сыграют.
//
// ————— и обратная сторона того же счёта —————
//
// Всё сказанное выше — про вора. Но у каждой находки есть вторая сторона: пак,
// у которого взяли. Про него до сих пор не говорилось ничего, а спрашивают
// про него ровно так же часто: открыв пак, хочется знать не только «списано ли
// это откуда-то», но и «растащили ли это потом».
//
// Считается оно тем же проходом и из тех же самых находок — просто записывается
// не вору, а донору: его тема получает список тех, кто позже поставил её вопросы
// себе, вместе с числом вопросов у каждого. На карточке такая тема красится
// зелёным — это не обвинение паку, а его заслуга (см. web/card.js).

import crypto from 'node:crypto';
import { buildAuthorKey } from './keys.js';

/**
 * Строка, приведённая к скелету: нижний регистр, «ё» — «е», всё, что не буква
 * и не цифра, схлопнуто в один пробел, края обрезаны.
 *
 * Без этого «Кто изображён на фото?» и «кто изображен на фото» были бы двумя
 * разными вопросами, а списавший — невиновным. Знаки препинания выброшены
 * нарочно: при переносе пака из редактора в редактор кавычки и тире меняются
 * сами собой, и держаться за них значит ловить только тех, кто копировал файл
 * целиком.
 */
export function skeleton(text) {
	return String(text ?? '')
		.toLowerCase()
		.replace(/ё/g, 'е')
		.replace(/[^\p{L}\p{N}]+/gu, ' ')
		.trim();
}

/**
 * Отпечаток немого вопроса: у него нет ни текста, ни ответа — только имя
 * приложенного файла, и сравнивать по нему нечего (см. questionFingerprint).
 *
 * Ноль выбран затем, что в свёртке он и так означает «здесь ничего»: настоящий
 * отпечаток — восемь байт SHA-1, и выпасть ровно нулём они не могут иначе как
 * раз в жизни вселенной. Место такому вопросу в свёртке пишется как всем,
 * а вот в сравнение он не идёт: decodePrints не кладёт MUTE ни в byPrint,
 * ни в weights, и дальше по правилу его попросту нет.
 */
export const MUTE = 0n;

/**
 * Отпечаток вопроса: sha1(текст + "\0" + файлы + "\0" + ответ)[0..8] одним
 * 64-битным числом.
 *
 * Нулевые байты между кусками стоят не для красоты. Без них вопрос «Кто это?»
 * с ответом «Гагарин» и вопрос «Кто это? Гагарин» с пустым ответом дали бы
 * один и тот же отпечаток — а это разные вопросы.
 *
 * Совсем пустой вопрос отпечатка не получает вовсе (null): в паках попадаются
 * вопросы-заглушки без текста, файла и ответа, и все они сошлись бы в один
 * отпечаток, который тут же стал бы общим местом на пол-базы.
 *
 * Вопрос из одного имени файла получает MUTE — «вопрос есть, а улики нет»
 * (см. шапку модуля). Это не то же самое, что пустой: пустого вопроса
 * за столом не было вовсе, а немой был, и в размер темы он входит наравне
 * с остальными.
 */
export function questionFingerprint({ text, media, answer }) {
	const bare = skeleton(text);
	const answered = skeleton(answer);
	const body = `${bare}\0${skeleton(media)}\0${answered}`;

	if (body === '\0\0') {
		return null;
	}

	if (bare === '' && answered === '') {
		return MUTE;
	}

	return crypto.createHash('sha1').update(body).digest().readBigUInt64BE(0);
}

/**
 * Сколько байт занимает один вопрос в свёртке: отпечаток, его место и вес
 * приложенных к нему файлов.
 *
 * Место (номер раунда и номер темы) лежит рядом с отпечатком, а не выводится
 * потом из разбора, по двум причинам. Во-первых, метку получает тема, и без
 * места вопрос не с чем связать. Во-вторых, темы у пака хранятся уже готовыми
 * (поле rounds), и вычислять по ним «какой вопрос где» пришлось бы заново
 * на каждом пересмотре — а пересмотр идёт по всей библиотеке сразу.
 *
 * Вес — четыре байта, сумма размеров файлов вопроса как они лежат в архиве
 * (см. sameWeight): по нему отсеиваются совпадения имени при разном файле.
 */
export const RECORD = 16;

/** Свёртки, снятые до появления веса: те же двенадцать байт без последних четырёх. */
export const RECORD_V1 = 12;

/**
 * Какой сейчас вид у свёртки. Лежит рядом с ней в базе (pack_prints.version):
 * читать двенадцатибайтные записи как шестнадцатибайтные нельзя, а длиной
 * свёртки их не различить — сорок восемь байт делится и на то, и на другое.
 *
 * Второй вид добавил к записи вес файлов, третий — немой вопрос: у свёрток
 * первых двух видов вопрос из одного имени файла записан обычным отпечатком
 * и потому совпадает с таким же в чужом паке, хотя улики за этим никакой нет
 * (см. MUTE). Длина записи у второго и третьего вида одна и та же — разошлось
 * не устройство свёртки, а правило, по которому её снимали, и узнать одно
 * от другого можно только по записанному рядом номеру.
 *
 * Отсюда и разница в спешке. Свёртки первого вида не переснять было не страшно:
 * вес нужен, только чтобы отменить уже найденное совпадение, и без него
 * правило работало ровно как работало. Свёртки второго вида врут в другую
 * сторону — находят там, где находить нечего, — и переснимать их стоит
 * (см. fetchPrints в src/indexer/backfill.js).
 *
 * Четвёртый вид — про то, что считается содержимым вопроса. Раньше в отпечаток
 * шло всё, что нашлось внутри <question>: и ответная часть (картинка, которую
 * показывают после ответа), и обвязка спецвопроса — название темы кота, его
 * цена, способ передачи. Ни то, ни другое вопросом не является: один и тот же
 * вопрос, к которому двое приложили разные картинки ответа, давал разные
 * отпечатки, а обычный вопрос, превращённый в кота в мешке, переставал
 * совпадать сам с собой. Теперь считается только то, что спрашивают
 * (см. questionSide в src/siq.js), — и спецвопрос плагиатом быть не мешает.
 *
 * Переснимать четвёртым видом надо всю библиотеку: отпечатки третьего вида
 * и четвёртого — это разные числа у одного и того же вопроса, и совпасть
 * между собой они не могут. Пока пак не переснят, он сравнивается только
 * с такими же непереснятыми.
 *
 * ————— почему до сих пор четвёртый —————
 *
 * Номер поднимается тогда и только тогда, когда меняется число, которое здесь
 * получается: правило подсчёта отпечатка (questionFingerprint), то, что в него
 * идёт (questionSide и questionParts в src/siq.js), или устройство самой свёртки
 * (RECORD). Ничего из этого с четвёртого вида не менялось, и проверено это
 * не рассуждением, а прямой сверкой 30 августа 2026: у двадцати восьми паков
 * заново скачан content.xml, отпечатки сняты нынешним кодом и сравнены
 * с лежащими в базе — совпали байт в байт, все двадцать восемь.
 *
 * Менялось рядом другое, и оно номера не требует. Считать, много ли в паке
 * чужих ссылок (countMediaRefs), — это про то же самое содержимое, но не про
 * отпечаток: свёртка от этого не меняется ни на байт. Переснимать ради него
 * библиотеку всё равно приходится — числа эти снимает тот же разбор, — но
 * очередь на это собирается своим условием, а не поднятым номером вида
 * (см. fetchPrints в src/indexer/backfill.js). Разница не формальная: поднятый
 * номер объявляет несравнимыми уже снятые отпечатки, то есть на несколько ночей
 * ослепляет правило по всей библиотеке. Делать это ради того, что отпечатков
 * не касается, было бы прямым вредом.
 *
 * Если правило всё-таки поменяли, а номер поднять забыли, — есть ключ
 * `--reprints`: он переснимает всех подряд, не спрашивая номера
 * (см. src/indexer/options.js).
 */
export const PRINTS_VERSION = 4;

/** Сколько байт в записи свёртки такого вида. Третий и четвёртый записаны как второй. */
export const recordSize = version => (version >= 2 ? RECORD : RECORD_V1);

/** Сколько вопросов лежит в свёртке. */
export const countPrints = (blob, version = PRINTS_VERSION) =>
	Math.floor((blob?.length ?? 0) / recordSize(version));

/**
 * Отпечатки всех вопросов пака одной свёрткой.
 *
 * Двоичной, а не JSON: у пака сотня вопросов, у библиотеки — миллион с лишним,
 * и то же самое списком чисел в тексте весило бы вчетверо больше и читалось бы
 * разбором JSON на каждом пересмотре.
 *
 * @param {Array<{round: number, theme: number, text: string, media: string, answer: string,
 *        mediaBytes: number}>} questions вопросы как их отдал разбор
 *        (см. collectQuestions в src/siq.js)
 * @returns {Buffer}
 */
export function encodePrints(questions) {
	const kept = [];

	for (const question of questions ?? []) {
		const fp = questionFingerprint(question);

		// Немой вопрос (MUTE) записывается наравне со всеми — выбросить его
		// значило бы уменьшить тему, в которой он стоит, а размер темы решает,
		// метить ли её целиком (см. themeSizes в decodePrints). Вопрос там был,
		// просто судить по нему нечего
		if (fp !== null) {
			kept.push({ fp, round: question.round, theme: question.theme, bytes: question.mediaBytes ?? 0 });
		}
	}

	const buffer = Buffer.allocUnsafe(kept.length * RECORD);

	kept.forEach((item, index) => {
		const at = index * RECORD;
		buffer.writeBigUInt64BE(item.fp, at);
		buffer.writeUInt16BE(Math.min(65535, item.round), at + 8);
		buffer.writeUInt16BE(Math.min(65535, item.theme), at + 10);
		// Вес обрезан четырьмя гигабайтами, и это не ограничение: медиафайл
		// такого размера в пак не кладут — сам пак не пускают и вчетверо меньшим
		buffer.writeUInt32BE(Math.min(0xffffffff, Math.round(item.bytes)), at + 12);
	});

	return buffer;
}

/**
 * Свёртка обратно в то, чем по ней судят.
 *
 * `byPrint` — отпечаток и все места, где он в этом паке стоит. Повторы внутри
 * одного пака схлопываются в один отпечаток нарочно: вопрос, поставленный
 * в пак дважды, — это один вопрос, и считать его за два значило бы дарить долю
 * тому, кто повторился. Места при этом запоминаются оба: чужих вопросов
 * за столом всё-таки два.
 *
 * `themeSizes` — сколько вопросов в каждой теме. По ним отличается тема,
 * пришедшая из чужого пака целиком, от темы, откуда взяли пару вопросов:
 * помечены сайтом обе, но говорят они разное и красятся по-разному. Немые
 * вопросы в размер темы входят: за столом они есть, и делать вид, что тема
 * из семи вопросов состоит из трёх, — значит объявить её чужой целиком вдвое
 * охотнее, чем следует.
 *
 * `weights` — вес приложенных файлов у каждого отпечатка. По нему отменяется
 * совпадение, у которого сошлись имя файла и ответ, а сам файл разный
 * (см. sameWeight). Ноль значит «неизвестно»: у вопроса без файлов веса нет
 * вовсе, а у свёрток прежнего вида его не записывали.
 *
 * @param {Buffer|Uint8Array|null} blob
 * @param {number} version вид свёртки (pack_prints.version)
 */
export function decodePrints(blob, version = PRINTS_VERSION) {
	const byPrint = new Map();
	const themeSizes = new Map();
	const weights = new Map();
	const record = recordSize(version);

	if (!blob || blob.length < record) {
		return { byPrint, themeSizes, weights };
	}

	const buffer = Buffer.isBuffer(blob) ? blob : Buffer.from(blob.buffer, blob.byteOffset, blob.byteLength);

	for (let at = 0; at + record <= buffer.length; at += record) {
		const fp = buffer.readBigUInt64BE(at);
		const place = { round: buffer.readUInt16BE(at + 8), theme: buffer.readUInt16BE(at + 10) };
		const key = `${place.round}:${place.theme}`;

		themeSizes.set(key, (themeSizes.get(key) ?? 0) + 1);

		// Немой вопрос дальше размера темы не идёт: сравнивать его не с чем,
		// и один общий на всех отпечаток MUTE иначе слепил бы все безымянные
		// медиавопросы библиотеки в один вопрос, который есть у каждого
		if (fp === MUTE) {
			continue;
		}

		if (record >= RECORD && !weights.has(fp)) {
			weights.set(fp, buffer.readUInt32BE(at + 12));
		}

		const known = byPrint.get(fp);

		if (known) {
			known.push(place);
		} else {
			byPrint.set(fp, [place]);
		}
	}

	return { byPrint, themeSizes, weights };
}

/**
 * Один ли это файл. По весу — то есть по размеру приложенных к вопросу файлов
 * в байтах.
 *
 * Отпечаток вопроса считает имя файла наравне с текстом и ответом, и обычно
 * этого хватает: имя переезжает из пака в пак нетронутым, потому что папку
 * Audio перекладывают целиком. Но имя — не файл. «01.mp3», «Опенинг.mp3»,
 * «1.jpg» стоят в разных паках с разным содержимым, а ответ у вопроса
 * «назовите аниме» задаёт не пак, а само произведение: два человека,
 * независимо взявшие один опенинг, дадут одинаковый ответ при одинаково
 * безликом имени файла. Вес разводит эти два случая: тот же файл весит
 * то же самое, а другой файл — другое.
 *
 * Ноль с любой стороны значит «неизвестно», и тогда сравнивать нечем:
 * у вопроса без файлов веса нет, а у паков, чьи отпечатки сняты до появления
 * этого правила, он не записан. Неизвестность толкуется в пользу находки —
 * так же, как раньше, когда веса не было ни у кого: иначе одна правка правил
 * разом стёрла бы все находки по всей библиотеке.
 */
function sameWeight(a, b) {
	return a === 0 || b === 0 || a === b;
}

/**
 * Когда содержимое пака появилось на свет. Позднее из двух: дата сообщения
 * в обсуждении и дата самого файла в ВК.
 *
 * ————— зачем понадобилось второе —————
 *
 * Файл под сообщением заменяют. Сообщение при этом остаётся тем же и датой
 * своей не двигается — а в нём уже другой пак. Судить по одной дате сообщения
 * значит верить, что под постом 2017 года лежит пак 2017 года, — а лежать там
 * может что угодно, вплоть до чужого пака, выложенного в прошлом месяце.
 * Тогда правило переворачивается с ног на голову: старый пост объявляется
 * первоисточником, а настоящий автор, выложивший месяц назад, — вором.
 *
 * ВК про это говорит сам: у документа есть своя дата — когда он в ВК появился
 * (см. buildComments в src/vkapi.js, поле fileTs). Заменили файл — дата новая,
 * и пак больше не старше того, у кого списали.
 *
 * Берётся позднее из двух, а не дата файла вместо даты сообщения. Файл,
 * загруженный в ВК раньше, чем выложен в обсуждение, — случай обычный
 * (лежал в документах, потом выложили), и старшинство ему это не даёт: до поста
 * его никто не видел. А вот файл, загруженный позже поста, — это ровно тот
 * случай, ради которого всё и заведено.
 *
 * ————— почему не номер строки —————
 *
 * Номер строки старшинством не является, и это не мелочь: номера раздаёт
 * порядок обхода обсуждений, темы читаются с конца, а старое подбирается
 * потом — пак 2019 года запросто получает номер больше, чем пак 2026-го.
 * Судить по номеру значило бы объявить вором того, кто выложил первым.
 * Номер решает только спор двух паков с одинаковой отметкой.
 */
export function contentTs(row) {
	const posted = row.vk_ts ?? null;
	const uploaded = row.file_ts ?? null;

	if (posted === null) {
		return uploaded;
	}

	return uploaded === null ? posted : Math.max(posted, uploaded);
}

/**
 * С какого мгновения содержимое пака могло оказаться на свету. Дата поста,
 * а не дата содержимого.
 *
 * Ровно ту же пару чисел, что и contentTs, читает эта, но с другого конца.
 * contentTs отвечает «когда содержимое точно было видно», а тут — «раньше
 * этого его точно не было видно». У обычного пака оба ответа совпадают: файл
 * лежит под постом с самого поста. Расходятся они у пака, чей файл моложе
 * поста, — и расстояние между ними и есть то окно неизвестности, ради
 * которого эта дата и понадобилась (см. inTheDark).
 *
 * Пост без даты (такого в базе нет, но бывает) отдаёт дату содержимого:
 * неизвестности тогда нет, потому что нет и второго конца.
 */
export function contentSince(row) {
	return row.vk_ts ?? contentTs(row);
}

/**
 * Кто раньше. По отметке времени, а при равных отметках — по меньшему номеру.
 *
 * Пак без отметки времени старшим не бывает: про него неизвестно, когда он
 * появился, и назначать его источником — значит выдумывать. Такой пак остаётся
 * в базе обычным паком, просто донором ни для кого не становится.
 */
function earlier(a, b) {
	if (a.ts === null) {
		return false;
	}

	if (b.ts === null) {
		return true;
	}

	return a.ts === b.ts ? a.id < b.id : a.ts < b.ts;
}

/**
 * Окно неизвестности: не вышел ли донор уже после поста того, кого судим.
 *
 * ————— откуда берётся окно —————
 *
 * Дата содержимого (contentTs) берётся позднейшей из двух — поста и файла, —
 * и делает это ради одного случая: файл под старым постом подменили,
 * и старшинство поста подменённому содержимому не принадлежит. Мерка верная,
 * но у неё есть вторая сторона, которую она задевает зря.
 *
 * Файл под постом заменяют не только подменой. Автор перезаливает свой же пак:
 * поправил вопросы, добавил раунд, или ВК потерял документ — и человек кладёт
 * его заново. В библиотеке это видно пачками: у одного автора шесть паков
 * 2018 года с датой файла 17 июня 2023-го — он выложил их все за один вечер.
 * У такого пака дата содержимого уезжает на пять лет вперёд, а вместе с ней
 * и приговор: всё, что вышло за эти пять лет, оказывается старше него,
 * и собственные его вопросы, стоявшие в нём с 2018 года, объявляются взятыми
 * у тех, кто взял их у него.
 *
 * Промежуток между постом и файлом (см. contentSince) и есть окно: про пак
 * известно, что нынешнее его содержимое было на свету к дате файла, и больше
 * ничего. Донор, вышедший до поста, попасть в пак мог при любом чтении;
 * донор, вышедший внутри окна, — только если файл действительно подменили.
 *
 * ————— чего окно не меняет —————
 *
 * Обратной стороны мерки оно не трогает вовсе: донором подменённый пак
 * по-прежнему не станет — старшинство считает earlier по contentTs,
 * и первоисточником старый пост с новым файлом не объявится. То есть ровно то,
 * ради чего дата файла заведена, остаётся на месте. Меняется одно: кого
 * по находке из окна можно объявить вором (см. reviewPlagiarism).
 */
function inTheDark(donor, entry) {
	return entry.since !== null && entry.since < entry.ts
		&& donor.ts !== null && donor.ts >= entry.since;
}

/**
 * Один ли это человек. Три признака, и достаточно любого.
 *
 * Страница ВК (vk_author_url) — главный: имена в ВК меняют, адрес страницы нет.
 * Подпись внутри файла (authors_key) ловит того, кто перевыложил свой же пак
 * с другого аккаунта, не тронув файла.
 *
 * Третий — имя автора сообщения — добавлен по живому случаю и снимает ровно
 * одного: «Общие знания №3» Станислава Бонанчика списан у «SIGame
 * Развлекательный №2» Станислава Бонанчика. Две разные страницы ВК
 * (bonanchik04 и id863765889), две разные подписи в файле («Lord» и
 * «Lord_Buba») — и очевидно один человек. Без этой проверки в улове сидел бы
 * он, а не вор.
 *
 * Пустые значения не сравниваются вовсе: пак без подписи в файле совпал бы
 * по ней с половиной базы, и вся проверка выродилась бы в «все свои».
 */
function samePerson(a, b) {
	return (a.url !== '' && a.url === b.url)
		|| (a.authors !== '' && a.authors === b.authors)
		|| (a.author !== '' && a.author === b.author);
}

/**
 * Пак в том виде, в каком его читает разбор: только то, по чему выносится
 * приговор, и ничего больше. Свёртка отпечатков здесь уже разложена и дальше
 * не держится.
 */
function toEntry(row) {
	const { byPrint, themeSizes, weights } = decodePrints(row.prints, row.prints_version ?? 1);

	return {
		id: row.id,
		name: row.name ?? '',
		// Не дата сообщения, а дата содержимого: файл под сообщением меняют,
		// а сообщение датой не двигается (см. contentTs)
		ts: contentTs(row),
		// …и нижний край той же даты: раньше поста содержимое видно не было.
		// У обычного пака совпадает с ts, у перезалитого — нет (см. inTheDark)
		since: contentSince(row),
		url: (row.vk_author_url ?? '').trim(),
		author: buildAuthorKey(row.vk_author ?? ''),
		authors: buildAuthorKey(row.authors_key ?? ''),
		questions: byPrint,
		themeSizes,
		weights,
	};
}

/**
 * Сколько доноров запоминается у пака.
 *
 * Список этот делает две работы. Первая — та, ради которой заведён: на карточке
 * человек читает, откуда взято, и дальше первых двух-трёх строк не смотрит.
 * Вторая появилась позже: по нему карточка узнаёт имя донора у темы, у которой
 * донор один и потому списком с именами не записан (см. places ниже). Ради
 * второй предел и поднят с пяти до дюжины: донор, в список не попавший,
 * оставляет тему с номером вместо названия.
 *
 * Дюжина — не «на всякий случай»: паков, у которых доноров больше, в библиотеке
 * единицы, и у них это уже не «откуда взято», а простыня, которую всё равно
 * никто не дочитает.
 */
const MAX_SOURCES = 12;

/**
 * Сколько доноров запоминается у одной темы и сколько воров — у одной
 * обворованной темы. Пять на тему хватает с запасом: тема из семи вопросов,
 * собранная из шести разных паков, — случай, которого в библиотеке нет,
 * а подсказка длиной в шесть названий читаться перестаёт.
 */
const MAX_PER_THEME = 5;

/** Доля до тысячных — как и везде в этом проекте (см. topics.js). */
const round = value => Math.round(value * 1000) / 1000;

/**
 * Полный пересмотр базы: кто у кого списал.
 *
 * Пересмотр именно полный, и добором его не заменить. Пак, найденный сегодня
 * в старой теме обсуждения и выложенный в 2019 году, меняет старшинство сразу
 * у всех, кого уже проверили: вчерашний «первоисточник» оказывается вором.
 * Поэтому шаг всякий раз раскладывает базу заново — это секунды и ни одного
 * похода в сеть, а половинчатая проверка врала бы уверенно.
 *
 * Строки берутся любым перечислением, а не готовым массивом, нарочно: свёртки
 * отпечатков всей библиотеки — это тринадцать мегабайт, и держать их разом
 * незачем. Здесь от каждого пака остаются одни числа, а свёртка живёт ровно
 * до конца своего витка. Индексатор этим и пользуется: читает базу потоком
 * (см. шаг plagiarism).
 *
 * @param {Iterable} rows строки packages: id, name, vk_ts, vk_author,
 *        vk_author_url, authors_key, prints (свёртка из pack_prints)
 * @param {object} limits пороги из settings.js
 * @returns {{verdicts: Map<number, object>, taken: Map<number, object>, stats: object}}
 *        приговоры только у тех паков, у кого нашёлся хоть один чужой вопрос;
 *        у остальных метки нет, и это не то же самое, что «проверен и чист» —
 *        это «ничего не нашлось». Рядом — обратная сторона тех же находок:
 *        у кого что взяли и кто взял (taken)
 */
export function reviewPlagiarism(rows, limits) {
	const entries = [];

	for (const row of rows) {
		entries.push(toEntry(row));
	}

	// Кто где встречается. Ключ — отпечаток вопроса, значение — паки, в которых
	// он есть. Миллион с лишним ключей и столько же коротких списков: это
	// и есть та самая «разложенная в память база»
	const holders = new Map();

	for (const entry of entries) {
		for (const fp of entry.questions.keys()) {
			const known = holders.get(fp);

			if (known) {
				known.push(entry);
			} else {
				holders.set(fp, [entry]);
			}
		}
	}

	// Общее место: вопрос, встречающийся в стольких паках, — фольклор своей
	// игры, а не чья-то собственность. «Что тяжелее, килограмм пуха или
	// килограмм железа» принадлежит всем. Такие отпечатки выбрасываются
	// совсем — и из числителя, и из знаменателя: считать их заимствованными
	// нельзя, но и записывать паку в заслугу как «свой вопрос» тоже
	const common = new Set();

	for (const [fp, list] of holders) {
		if (list.length >= limits.plagiarismCommonPacks) {
			common.add(fp);
		}
	}

	// Донор вопроса — тот, у кого он стоит раньше всех. Сортируем держателей
	// один раз здесь, а не ищем самого раннего на каждый вопрос каждого пака:
	// дальше остаётся сравнение двух пар чисел
	for (const list of holders.values()) {
		list.sort((a, b) => (earlier(a, b) ? -1 : 1));
	}

	const verdicts = new Map();

	// Обратная сторона находок: кому что вернуть. Ключ — номер донора, значение —
	// его обворованные темы вместе с теми, кто их вопросы позже поставил себе.
	// Складывается тем же проходом: находка одна, а сторон у неё две
	const taken = new Map();
	const stats = { packs: 0, withPrints: 0, mute: 0, fingerprints: holders.size, common: common.size, flagged: 0, robbed: 0 };

	for (const entry of entries) {
		stats.packs++;

		// «Отпечатки есть» считается по местам, а не по отпечаткам: пак, у
		// которого все вопросы немые, свёртку имеет, и звать на него шаг prints
		// незачем — он снимет ровно то же самое. Такие паки считаются отдельно
		// (mute): для правила они пусты, но пусты навсегда, а не до пересъёмки
		if (entry.themeSizes.size > 0) {
			stats.withPrints++;

			if (entry.questions.size === 0) {
				stats.mute++;
			}
		}

		// Свои вопросы — всё, кроме общих мест
		const own = [...entry.questions.keys()].filter(fp => !common.has(fp));

		// Пак из десятка вопросов, списанный целиком, — это «сто процентов»,
		// которым цена ноль: столько вопросов сходится и по случайности
		if (own.length < limits.plagiarismMinQuestions) {
			continue;
		}

		// Откуда взят каждый заимствованный вопрос
		const found = [];

		for (const fp of own) {
			const weight = entry.weights.get(fp) ?? 0;

			// Держатели уже отсортированы по старшинству, поэтому первый же чужой
			// и более ранний — и есть донор. Свои паки пропускаются молча:
			// перевыложить собственный пак со второго аккаунта — не воровство.
			// Разошедшийся вес пропускается так же молча: имя файла и ответ
			// сошлись, а файл разный, — значит, это не тот же вопрос (см. sameWeight)
			const donor = holders.get(fp).find(other => earlier(other, entry)
				&& !samePerson(other, entry)
				&& sameWeight(weight, other.weights.get(fp) ?? 0));

			if (!donor) {
				continue;
			}

			// Донор найден — а не сидит ли он в окне неизвестности этого пака,
			// решает inTheDark. Остальных держателей на этот счёт спрашивать
			// незачем: список отсортирован, и найденный — самый ранний
			// из подходящих; если уж он попал в окно, то и все прочие в нём
			found.push({ fp, donor, dark: inTheDark(donor, entry) });
		}

		if (found.length === 0) {
			continue;
		}

		// Находки из окна неизвестности: файл у пака моложе поста, а донор вышел
		// уже после поста (см. inTheDark). Читаются они двояко — либо под старым
		// постом подменили файл, либо автор перезалил свой же пак, а вопросы
		// стояли в нём с самого начала.
		//
		// Развести эти два чтения нечем, кроме доли. Подмена — это чужой файл
		// целиком или почти: у пака 7695 из окна пришло 86% вопросов, и все
		// от одного донора, — отмахнуться от такой находки значило бы открыть
		// дыру ровно там, где дата файла и заведена. А перезаливка своего — это
		// вопрос-другой из полутора сотен: у трёх «Аниме паков от GoldensFire»,
		// выложенных в 2025 году и перезалитых в 2026-м, из окна пришло по
		// одному-два вопроса — ровно те, которые потом взяли у них самих.
		// Объявлять по ним вором того, кто выложил пак первым, нельзя.
		//
		// Порог — тот же, с которого чужое считается заметной долей
		// (plagiarismPartialShare): ниже него приговор всё равно был бы «trace»,
		// то есть «единичные чужие вопросы», а единичное совпадение внутри окна
		// перезаливка объясняет не хуже подмены. Отброшенные находки
		// не записываются никуда: сказать по ним нечего ни про вора, ни про
		// донора — неизвестно даже, кто из них кто.
		const dark = found.filter(mark => mark.dark);

		const marks = dark.length > 0 && dark.length / own.length < limits.plagiarismPartialShare
			? found.filter(mark => !mark.dark)
			: found;

		if (marks.length === 0) {
			continue;
		}

		// Сколько вопросов дал каждый донор. Складывается после отбора, а не
		// в самом витке: у отложенных находок доноров нет вовсе
		const byDonor = new Map();

		for (const { donor } of marks) {
			byDonor.set(donor, (byDonor.get(donor) ?? 0) + 1);
		}

		const share = marks.length / own.length;
		const ranked = [...byDonor.entries()].sort((a, b) => b[1] - a[1] || a[0].id - b[0].id);
		const top = ranked[0][1] / marks.length;

		// Чьи имена уедут вместе с паком. Тема, у которой донор один и попал сюда,
		// имени при себе не держит — карточка возьмёт его отсюда; тема, донор
		// которой в список не влез, обязана назвать его сама, иначе на карточке
		// вместо названия окажется голый номер
		const named = new Set(ranked.slice(0, MAX_SOURCES).map(([donor]) => donor.id));

		// Сколько чужих вопросов в паке. Складывается по местам, а не по
		// отпечаткам, и разница тут есть: вопрос, поставленный в пак дважды, —
		// это два вопроса на столе, хотя доля считает его за один. Спрашивают-то
		// именно про вопросы: «на скольких чужих сыграют»
		let questions = 0;

		// Где в раундах стоят заимствованные вопросы и чьи они. Тема — самое
		// мелкое, что показывает сайт, поэтому вопросы складываются по темам:
		// отсюда шаг проставляет полю src номер донора, и у солянки эти номера
		// разные — каждая обворованная тема получает свою ссылку
		const themes = new Map();

		// То же самое, но с другого конца: где эти вопросы стоят у самого донора.
		// Места разные — в его паке та же тема стоит в своём раунде под своим
		// номером, — и вывести одно из другого нельзя
		const donorThemes = new Map();

		for (const { fp, donor } of marks) {
			const here = entry.questions.get(fp);

			// Темы, где этот вопрос уже засчитан как отдельный. Вопрос, поставленный
			// в тему трижды, — три места, но один вопрос: у донора он стоит
			// единожды, и донор про него скажет «1 из 1». Чтобы подсказки двух
			// паков не спорили между собой, тема помнит и то, и другое
			const counted = new Set();

			for (const place of here) {
				questions++;

				const key = `${place.round}:${place.theme}`;
				const known = themes.get(key)
					?? { round: place.round, theme: place.theme, borrowed: 0, donors: new Map(), distinct: new Map() };

				known.borrowed++;
				known.donors.set(donor, (known.donors.get(donor) ?? 0) + 1);

				if (!counted.has(key)) {
					counted.add(key);
					known.distinct.set(donor, (known.distinct.get(donor) ?? 0) + 1);
				}

				themes.set(key, known);
			}

			let mine = donorThemes.get(donor);

			if (!mine) {
				mine = new Map();
				donorThemes.set(donor, mine);
			}

			const noted = new Set();

			for (const place of donor.questions.get(fp)) {
				const key = `${place.round}:${place.theme}`;
				const known = mine.get(key) ?? { round: place.round, theme: place.theme, n: 0, x: 0 };

				known.n++;

				// Сколько раз этот вопрос стоит у взявшего. Обычно столько же,
				// сколько у донора, но бывает, что взявший ставит один вопрос
				// в тему несколько раз, — и тогда у него «3 из 5», а здесь «1 из 1».
				// Без этого числа подсказки двух паков противоречили бы друг другу
				if (!noted.has(key)) {
					noted.add(key);
					known.x += here.length;
				}

				mine.set(key, known);
			}
		}

		// Метку получает всякая тема, где нашёлся хоть один чужой вопрос. Порога
		// в половину темы здесь больше нет, и убран он не из строгости: он ставил
		// сайт перед выбором «обвинить или промолчать», а промолчать про тему,
		// где чужих вопросов два из семи, — тоже неправда.
		//
		// Вместо порога наверх едут числа: сколько вопросов темы чужие (`n`)
		// и сколько их в теме всего (`of`). По ним карточка и решает, как
		// показать: тема, списанная целиком, красится уликой, тема, откуда взяли
		// часть, — оранжевым, и подсказка у обеих говорит, сколько именно
		// вопросов и чьих (см. web/card.js).
		const places = [...themes.entries()].map(([key, item]) => {
			// Доноры темы, от давшего больше всех к давшему меньше. Раньше
			// сюда доезжал один — первый из этого же списка, — и подсказка
			// говорила «5 вопросов из «Солянки»» там, где «Солянка» дала три,
			// а два пришли ещё откуда-то. Теперь едут все: тема, собранная
			// из трёх паков, так и называет три.
			const ranked = [...item.donors.entries()]
				.sort((a, b) => b[1] - a[1] || a[0].id - b[0].id);

			const [donor, n] = ranked[0];

			const place = {
				round: item.round,
				theme: item.theme,
				// Ссылка у темы одна и ведёт к тому, кто дал больше всех:
				// нажимают на название темы, а название одно
				source: donor.id,
				// Сколько вопросов дал именно он. Не «сколько чужого в теме
				// вообще»: у ссылки один адрес, и число при нём должно быть его
				n,
				// Размер темы. Нужен ровно для одного решения — вся тема пришла
				// оттуда или только часть её вопросов, — и потому едет вместе
				// с числом, а не считается на сайте: состава вопросов
				// у карточки нет
				of: entry.themeSizes.get(key) ?? item.borrowed,
			};

			// Список целиком записывается там, где донор не один или где его имени
			// нет в списке доноров пака. В остальных случаях он повторял бы то,
			// что уже сказано полями source и n, и лежал бы лишним весом
			// в каждой строке базы
			//
			// Повторы тоже требуют списка: сколько тут разных вопросов, а сколько
			// мест, полями source и n не сказать. Поле q — разных вопросов —
			// ставится, только когда их меньше, чем мест
			const repeated = ranked.some(([who, count]) => item.distinct.get(who) < count);

			if (ranked.length > 1 || !named.has(donor.id) || repeated) {
				place.donors = ranked.slice(0, MAX_PER_THEME).map(([who, count]) => {
					const distinct = item.distinct.get(who);

					return distinct < count
						? { id: who.id, name: who.name, n: count, q: distinct }
						: { id: who.id, name: who.name, n: count };
				});
			}

			return place;
		});

		// Слишком мало, чтобы записывать. По умолчанию порог — один вопрос,
		// то есть не отсекает ничего: один дословно совпавший вопрос
		// случайностью не бывает. Ручка эта на случай, если нижняя ступень
		// достанется половине библиотеки и метка превратится в обои
		if (questions < limits.plagiarismMinStolen) {
			continue;
		}

		verdicts.set(entry.id, {
			// Четыре ступени, а не «да/нет».
			//
			//   pack     — копия: чужого почти всё, и почти всё от одного донора;
			//   compiled — солянка: чужого почти всё, но собрано из нескольких;
			//   partial  — заметная доля чужого при своём костяке;
			//   trace    — единичные чужие вопросы.
			//
			// Разница между первыми двумя не косметическая: у копии один виноватый
			// и одна ссылка, у солянки их пять, и обещать ей «списано вот отсюда»
			// значило бы соврать. Третья же — не обвинение вовсе, а наблюдение,
			// и отбор «без копий чужих паков» её не трогает.
			//
			// Четвёртая заведена затем, чтобы отбор «чужих вопросов хотя бы
			// столько-то» имел на что опереться. Один дословно совпавший вопрос —
			// это не приговор паку, но это то, что человек ищет, когда
			// разбирается, кто у кого берёт; и молчать о нём, раз уж он найден,
			// было бы странно
			kind: share >= limits.plagiarismShare
				? (top >= limits.plagiarismDonorShare ? 'pack' : 'compiled')
				: (share >= limits.plagiarismPartialShare ? 'partial' : 'trace'),
			share: round(share),
			borrowed: marks.length,
			total: own.length,
			// Число чужих вопросов, а не доля: доля у пака уже есть, и вторая,
			// посчитанная по другому знаменателю, только сбивала бы с толку
			questions,
			// Название донора лежит рядом с номером нарочно: адрес страницы пака
			// складывается из номера и названия (см. packSlug в src/slug.js), и без
			// названия карточке пришлось бы ходить в D1 за каждым донором отдельно
			sources: ranked.slice(0, MAX_SOURCES).map(([donor, n]) => ({
				id: donor.id,
				name: donor.name,
				n,
				share: round(n / marks.length),
			})),
			places,
		});

		stats.flagged++;

		// Приговор записан — значит, находки настоящие, и вторую их сторону тоже
		// пора записать. До этой черты выход из витка случается четырежды
		// (мало своих вопросов, ни одной находки, мало чужих вопросов), и донор,
		// у которого «взяли» в непризнанной находке, обворованным не считается
		for (const [donor, mine] of donorThemes) {
			let victim = taken.get(donor.id);

			if (!victim) {
				victim = new Map();
				taken.set(donor.id, victim);
			}

			for (const [key, item] of mine) {
				const known = victim.get(key) ?? {
					round: item.round,
					theme: item.theme,
					of: donor.themeSizes.get(key) ?? 0,
					by: [],
				};

				// x — сколько раз эти вопросы стоят у взявшего; ставится, только
				// когда он их повторял
				known.by.push(item.x > item.n
					? { id: entry.id, name: entry.name, n: item.n, x: item.x }
					: { id: entry.id, name: entry.name, n: item.n });
				victim.set(key, known);
			}
		}
	}

	// Обворованные темы — в тот же вид, в каком лежат места вора: список готовых
	// строк, каждая про одну тему. Воры внутри строки — от взявшего больше всех
	stats.robbed = taken.size;

	const stolen = new Map();

	for (const [id, themes] of taken) {
		const places = [...themes.values()].map(item => ({
			round: item.round,
			theme: item.theme,
			of: item.of,
			by: item.by
				.sort((a, b) => b.n - a.n || a.id - b.id)
				.slice(0, MAX_PER_THEME),
		}));

		stolen.set(id, { places });
	}

	return { verdicts, taken: stolen, stats };
}
