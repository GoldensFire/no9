// Как называется обложка пака и по какому адресу её показывают.
//
// Ни настройка, ни название — правило именования файла. Имя уменьшенной копии
// считает и сборка статики (она эти копии делает), и Worker (он ставит его
// в ссылку), и домашний сайт; разойдись они — обложек не будет ни одной.
//
// Node-специфичного здесь нет и быть не может: этим пользуется и Worker.

/**
 * Имя уменьшенной копии обложки на хостинге.
 *
 * Формат один для всех — AVIF. Тот же кадр в нём весит вдвое меньше, чем в jpg
 * или webp, а обложки — самое тяжёлое, что отдаёт сайт: их под четыре сотни,
 * и на страницу их разом приходит два десятка. Браузер, который AVIF не понимает,
 * покажет вместо обложки квадрат с первой буквой названия (см. createLogo
 * в web/common.js) — некрасиво, но не сломано; таких браузеров с 2024 года нет.
 *
 * Правило лежит здесь, а не рядом со сборкой, потому что сойтись обязаны трое:
 * src/thumbs.js под этим именем делает копию, scripts/deploy-logos.js под ним же
 * кладёт её наверх, а cf/src/library/packs.js даёт на неё ссылку. Разойдись
 * они — обложек не будет ни одной.
 *
 * Расширение заменяется, а не приписывается: Content-Type Cloudflare ставит
 * по нему, и «511.jpg.avif» уехал бы как avif с jpg внутри.
 */
export function thumbName(logoFile) {
	return `${logoFile.replace(/\.[^./\\]*$/, '')}.avif`;
}

/**
 * Отпечаток, который приписывается к ссылке на обложку: /logos/thumb/511.avif?v=2.
 *
 * Нужен он из-за промаха, который стоил сайту всех свежих обложек разом.
 * Обложки отдаются из статики с вечным кэшем, и правило это (см. HEADERS
 * в scripts/deploy-logos.js) Cloudflare прикладывает к адресу, а не к файлу:
 * ответ «такой обложки нет» уезжал к браузеру с тем же самым
 * «max-age=31536000, immutable». А «такой обложки нет» по адресу обложки —
 * дело обычное: строка пака уезжает в D1 одной выкладкой, уменьшенная копия
 * появляется следующей, и всякий, кто открыл пак между ними, запоминал пустоту
 * на год вперёд и переспрашивать больше не приходил. Файл давно на месте,
 * а у человека квадрат с буквой — ровно это и было с паками 15915–15917 и 16554.
 *
 * Лечится это двумя вещами сразу, и обе нужны. Заголовок стал честным (сутки
 * вместо года), но до того, кто уже запомнил год, честный заголовок не доходит:
 * он не спрашивает. Достучаться до него можно только другим адресом — вот он.
 * Число ниже меняет адрес всем обложкам разом.
 *
 * Менять его руками больше не придётся: промах браузер теперь не запоминает
 * вовсе — ответ «такой обложки нет» приходит с «no-store» от собственного кода
 * Worker'а обложек (см. cf/logos/src/index.js). Но если когда-нибудь понадобится
 * заставить браузеры спросить заново — прибавьте единицу, и этого хватит.
 *
 * Тройка стоит ровно за этим: суточные промахи, запомненные до того, как
 * «no-store» появился, сами бы не забылись раньше суток, а обложки у тех,
 * кто их запомнил, не было бы всё это время (пак 21571, сентябрь 2026).
 */
export const LOGO_VERSION = 3;

/**
 * Ссылка на уменьшенную копию обложки — с отпечатком (см. LOGO_VERSION).
 *
 * Зовут её обе половины проекта, и приходят они разными путями: дома
 * src/server.js даёт ссылку на исходное имя файла (копию считает сам сервер,
 * когда её попросят), на хостинге cf/src/library/ — на имя готовой копии
 * из thumbName. Отпечаток при этом обязан быть один и тот же, поэтому
 * приписывается он здесь, а не в каждом из двух мест по-своему.
 */
export function logoUrl(name) {
	return `/logos/thumb/${name}?v=${LOGO_VERSION}`;
}

/**
 * Имя крупной копии обложки — той, что уезжает в чужое окно ссылкой на пак.
 *
 * Формат тот же, что и у обложки карточки, — AVIF (см. thumbName выше):
 * один формат на весь сайт и вдвое меньший вес при том же кадре. Отличается
 * копия не форматом, а размером: 144×144 для карточки ссылки мало — крупную
 * картинку там дают за размер (у Discord порог около трёхсот точек по стороне),
 * а квадратик с почтовую марку показывался значком сбоку от заголовка, если
 * показывался вовсе.
 *
 * Копия эта на сайте не показывается нигде и в вес его страниц не входит:
 * её просит только чужой сервер и только когда ссылкой поделились.
 */
export function previewName(logoFile) {
	// Разбор без выражения, в отличие от соседа выше: имя сюда приходит голым
	// («511.jpg»), путей в нём не бывает, и точка с конца ищется прямо.
	//
	// Расширение заменяется, а не приписывается, и по той же причине, что
	// и у обложки карточки: Content-Type Cloudflare ставит по нему.
	const dot = logoFile.lastIndexOf('.');

	return `${dot > 0 ? logoFile.slice(0, dot) : logoFile}.avif`;
}

/**
 * Ссылка на крупную копию — с тем же отпечатком, что и у обложки карточки.
 *
 * Лежит она у того же Worker'а обложек, соседней папкой: /logos/preview/…
 * против /logos/thumb/… (см. cf/logos/wrangler.jsonc).
 */
export function previewUrl(name) {
	return `/logos/preview/${name}?v=${LOGO_VERSION}`;
}

/**
 * Крупная копия по готовой ссылке на обложку карточки:
 * /logos/thumb/511.avif?v=3 → /logos/preview/511.avif?v=3.
 *
 * Нужен этот перевод затем, что имя файла обложки (logo_file в строке пака)
 * знает только тот, кто читал базу, — а страница пака собирается из уже
 * готового пака, где от него осталась одна ссылка (см. toPackage
 * в cf/src/library/packs.js). Разбирать её в разметке страницы руками значило
 * бы завести второе место, знающее, как обложки называются.
 *
 * null — «обложки у пака нет»: тогда и крупной копии нет тоже.
 */
export function previewFromLogo(logo) {
	if (!logo) {
		return null;
	}

	const name = logo.split('?')[0].split('/').pop();

	return name ? previewUrl(previewName(name)) : null;
}
