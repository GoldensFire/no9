/** Вид ответа на пачку: строка на картинку, по её номеру. */
export const BATCH_SCHEMA = {
	type: 'OBJECT',
	properties: {
		images: {
			type: 'ARRAY',
			items: {
				type: 'OBJECT',
				properties: {
					n: { type: 'INTEGER' },
					level: { type: 'STRING', enum: LEVELS },
					category: { type: 'STRING', enum: CATEGORIES },
					confidence: { type: 'STRING', enum: ['low', 'medium', 'high'] },
					reason: { type: 'STRING' },
				},
				required: ['n', 'level', 'category', 'confidence'],
			},
		},
	},
	required: ['images'],
};

/**
 * Части запроса на пачку: рубрика, потом картинки, каждая под своим номером.
 * Номер стоит текстом перед картинкой: без него модель на длинной пачке
 * сбивается со счёта и приписывает находку соседней.
 *
 * @param {{jpeg: Buffer}[]} images
 */
export function batchParts(images) {
	const parts = [{
		text: `${RUBRIC}\n\nНиже ${images.length} картинок, перед каждой её номер. Верни строку на каждую — ровно ${images.length} строк, номера от 1 до ${images.length}, ни одной не пропусти.`,
	}];

	images.forEach((image, index) => {
		parts.push({ text: `Картинка ${index + 1}:` });
		parts.push({ inlineData: { mimeType: 'image/jpeg', data: image.jpeg.toString('base64') } });
	});

	return parts;
}

