// Ник, который автор выбрал себе сам: под каким из своих написаний он стоит
// на сайте.
//
// ————— зачем —————
//
// Имя автора сайт выбирает сам: то написание подписи, которым подписано больше
// всего его паков (см. bestSpelling в src/indexer/authors.js и AUTHOR_NAME_SQL
// в src/keys.js). Правило честное, но слепое: человек, сменивший ник, ещё год
// стоит на сайте под старым — потому что старым подписано больше паков.
// Знает, как его звать, только он сам.
//
// ————— кому можно —————
//
// Выбрать можно только из того, что уже стоит в его паках: придумать себе
// новое имя здесь нельзя, иначе страница автора стала бы местом, где пишут
// что угодно. И только тому, за кем все его паки признаны без оговорок:
//
//   все паки человека выложены с одной страницы ВК — и это его страница
//     (pack_authors.canon_account, см. mergeAuthors в src/indexer/authors.js);
//   ни в одном из них нет соавтора — иначе подпись «Vasya & Petya» на общем
//     паке была бы не только его, и переименовать её значило бы распорядиться
//     чужим.
//
// Признанные хозяином сайта вручную (см. cf/src/library/verified.js) сюда
// не попадают нарочно: там нет страницы ВК, а значит, нет и того твёрдого
// признака, который здесь и требуется.
//
// ————— где это живёт —————
//
// Выбор делается наверху, на сайте, и лежит в D1 (таблица author_names, см.
// cf/schema.sql). Дома его забирает каждая выкладка (см. pullAuthorNames
// в scripts/deploy/author-names.js), чтобы сборка статики и ночной обход
// звали автора так же, как сайт.
//
// Ключ — номер страницы ВК, а не человек (canon_key): канон считает обход,
// и следующей ночью он может свести подписи иначе, — а страница ВК, с которой
// выложены паки, у человека та же. Условия проверяются не один раз при выборе,
// а при каждом применении (см. CHOSEN_NAMES_SQL): выложил человек совместный
// пак — и его выбор молча перестаёт действовать, а имя возвращается к обычному.
//
// Node-специфичного здесь нет и быть не может: файл читает Worker.

/**
 * Таблица выборов — домашняя копия. Наверху она заведена в cf/schema.sql
 * руками (тот файл не умеет импортировать) и с ссылкой на users, которой
 * дома нет; колонки же у них обязаны совпадать — выкладка переносит строки
 * как есть (см. pullAuthorNames в scripts/deploy/author-names.js).
 */
export const AUTHOR_NAMES_TABLE_SQL = `
	CREATE TABLE IF NOT EXISTS author_names (
		vk_id TEXT PRIMARY KEY,
		name TEXT NOT NULL,
		user_id INTEGER,
		updated_at INTEGER NOT NULL
	)
`;

/**
 * Действующие выборы: строка {k, name} на человека (canon_key), за которым
 * выбор сейчас признан.
 *
 * Выбор признан, когда совпало всё сразу:
 *
 *   выбранное написание стоит в паках этого человека и выложено с той самой
 *     страницы ВК, чей это выбор;
 *   у человека нет ни одной подписи, которая вела бы на другую страницу
 *     или не вела бы ни на какую (canon_account пуст — значит, подпись
 *     встречается у двух страниц);
 *   ни в одном его паке нет другого человека.
 *
 * Стоит это немного: выборов единицы, и каждый проверяется по указателям
 * ix_pack_authors_account и ix_pack_authors_canon, а соседи по паку — по
 * первичному ключу pack_authors.
 *
 * Порядок обхода назван прямо — CROSS JOIN от выборов к подписям и INDEXED BY
 * у подписей, — и это не украшение. Предоставленный сам себе, планировщик
 * идёт от другого конца: обходит все двадцать тысяч подписей ради GROUP BY
 * и для каждой ищет выбор. Дома это полсекунды, а у D1 прочитанные строки
 * идут по тарифу (та же беда и то же лечение — в ownersOfPack,
 * cf/src/library/authorship.js).
 */
export const CHOSEN_NAMES_SQL = `
	SELECT a.canon_key AS k, MIN(n.name) AS name
	FROM author_names n
	CROSS JOIN pack_authors a INDEXED BY ix_pack_authors_account
		ON a.canon_account = n.vk_id AND a.author = n.name
	WHERE NOT EXISTS (
		SELECT 1 FROM pack_authors o
		WHERE o.canon_key = a.canon_key AND (o.canon_account IS NULL OR o.canon_account <> n.vk_id)
	)
	AND NOT EXISTS (
		SELECT 1 FROM pack_authors m
		JOIN pack_authors x ON x.package_id = m.package_id AND x.canon_key <> m.canon_key
		WHERE m.canon_key = a.canon_key
	)
	GROUP BY a.canon_key
`;

/**
 * Записать действующие выборы в canon_name — главное имя человека, которым
 * его зовут профиль, уведомления, страница автора и топ.
 *
 * Прогоняется трижды и всегда одним текстом: ночным обходом дома (после
 * того как он заново свёл подписи, см. mergeAuthors), выкладкой наверху
 * сразу за заливкой паков — та переписывает строки подписей домашними —
 * и сайтом в ту же секунду, когда автор выбрал ник (см. setAuthorName
 * в cf/src/library/author-name.js).
 *
 * Обратного хода здесь нет и не нужно: выбор, переставший действовать, дома
 * пропадает сам — обход каждую ночь считает canon_name заново, — и наверх
 * приезжает уже обычное имя.
 */
export const APPLY_CHOSEN_NAMES_SQL = `
	UPDATE pack_authors SET canon_name = c.name
	FROM (${CHOSEN_NAMES_SQL}) AS c
	WHERE pack_authors.canon_key = c.k AND pack_authors.canon_name IS NOT c.name
`;
