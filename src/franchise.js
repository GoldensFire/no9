/**
 * Праздники: у них теперь своё поле разметки (h, см. HOLIDAYS в names.js),
 * и в области им места нет.
 *
 * Не запрет ради порядка, а починка двойного счёта. Тема «Рождество»
 * в новогоднем паке приходит от модели и праздником (h=newyear), и областью
 * («Рождество») сразу — и обе кучки считаются по одним и тем же темам.
 * Мишень пака тогда делится сама с собой: «Новый год 45%» и «Рождество 13%»
 * там, где на деле новогодних тем — больше половины, то есть ровно то,
 * что поле h и было заведено убрать.
 *
 * Ищется корнями, а не списком целиком: модель зовёт это как придётся —
 * «Новогодние традиции», «Новогодняя музыка», «Новый год в разных странах»,
 * — и все они об одном.
 */
const HOLIDAY_ROOTS = [
	'новогодн', 'новый год', 'нового года', 'новым годом', 'рождеств',
	'christmas', 'new year', 'хэллоуин', 'хеллоуин', 'halloween',
	'валентин', '23 февраля', '8 марта', 'день победы',
];

/**
 * Праздники, у которых корень совпал бы с обычным словом: «Пасха» внутри
 * «Пасхалок», а пасхалки в играх — законная тема и никакого отношения
 * к празднику не имеют. Такие сверяются словом целиком.
 */
const HOLIDAY_WORDS = new Set(['пасха', 'easter']);

function isHolidayName(text) {
	const key = normalize(text);

	if (!key) {
		return false;
	}

	return HOLIDAY_ROOTS.some(root => key.includes(root))
		|| key.split(' ').some(word => HOLIDAY_WORDS.has(word));
}

/**
 * Название — это тематика пака, а не то, чему пак посвящён?
 *
 * Проверяется по всему названию целиком, а не по словам: «Игры» тематика,
 * а «Голодные игры» — обычный фильм, и словарное правило зарубило бы второе
 * вместе с первым.
 *
 * Спрашивается не только у области, но и у произведения. Модель кладёт
 * «Games», «Movies», «Cinema» и в поле произведения тоже — и оттуда они идут
 * дальше в повторы пака: «пак возвращается к Games четыре раза» означает
 * ровно «в паке есть игры», то есть ничего. Правило поэтому одно на оба поля.
 *
 * Цена у этого одна и известная: группа «Кино» и подобные ей редкие совпадения
 * названия с тематикой теряются. Обмен того стоит — таких групп единицы,
 * а «Games» и «Movies» стояли предметом у семидесяти паков.
 */
export function isCategoryName(text) {
	return NOT_AREAS.has(normalize(text));
}

