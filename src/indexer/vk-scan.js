/**
 * Сверяет одно сообщение обсуждения с тем, что о нём уже записано.
 *
 * Раньше этот шаг только добавлял: увидел незнакомый файл — завёл пак, увидел
 * знакомый — прошёл мимо. Пока паки только прибывали, этого хватало; но сообщение
 * в обсуждении живое, автор его правит — дописывает, что починил, и перезаливает
 * файл. Ни то, ни другое база не замечала: на сайте оставалось первое описание
 * и первая, зачастую уже сломанная, версия пака.
 *
 * Что здесь сверяется:
 *   текст сообщения — это описание пака на карточке и часть того, по чему ищут;
 *   набор приложенных .siq — то есть сам пак.
 *
 * Чего заметить нельзя: сообщение, из которого файлы убрали все до единого.
 * Обход отдаёт только сообщения с вложениями (см. vkapi.js), и такое сообщение
 * до нас просто не доходит. Молчание тут честнее выдумки: удалённое сообщение
 * и сообщение, до которого не дошёл обход, выглядят совершенно одинаково.
 */
function syncComment(comment, useApi, tally) {
	const documents = comment.documents.filter(document => /\.siq$/i.test(document.fileName));

	if (documents.length === 0) {
		return;
	}

	const rows = knownInComment.all(comment.topicUrl, comment.id);
	const byKey = new Map(rows.map(row => [row.source_key, row]));

	// Пропавшими считаем только те файлы, которые до сих пор считались живыми.
	// Пак с мёртвой ссылкой и без того не показывается, и второй раз хоронить
	// его незачем — а вот в счёте он мешает: в сообщении, куда автор третий раз
	// перезаливает исправленный пак, «пропали два, появился один», и подмена
	// от простого исчезновения уже неотличима. Без давно похороненных остаётся
	// ровно то, что и произошло: один файл заменили другим.
	const alive = row => row.status !== 'gone' && row.status !== 'dead';
	const missing = rows.filter(row => alive(row) && !documents.some(document => document.key === row.source_key));
	const fresh = documents.filter(document => !byKey.has(document.key));
	const title = row => row.name ?? row.file_name ?? row.source_key;

	// Один файл ушёл, один пришёл — это почти наверняка не «минус пак, плюс пак»,
	// а перезалитый тот же самый: у ВК каждая загрузка получает свой номер, и по
	// номеру подмену от появления нового не отличить никак. Считаем подменой
	// и оставляем прежнюю строку — вместе с оценками, отметками «сыграно»
	// и местом в выдаче. Когда файлов больше одного, гадать нечем, и тогда
	// работает обычный разбор: чего нет — пропало, что появилось — новое.
	//
	// Оговорка про «этого документа больше нигде нет»: тот же файл нередко висит
	// сразу в двух сообщениях, и переселить строку на чужой ключ значит наткнуться
	// на запрет повторов в базе. Раньше это роняло весь обход темы целиком —
	// вместе с тысячами ещё не прочитанных сообщений.
	const takenElsewhere = fresh.length === 1 && knownDocument.get(fresh[0].key) !== undefined;

	if (missing.length === 1 && fresh.length === 1 && !takenElsewhere) {
		tally.pending.push({
			kind: 'replaced',
			apply: () => rebindDocument.run(fresh[0].key, fresh[0].url, fresh[0].fileName,
				fresh[0].fileTs ?? null, missing[0].id),
			say: `файл заменён: «${title(missing[0])}» -> ${fresh[0].fileName}`,
		});
	} else {
		for (const document of fresh) {
			// Документ, который в базе уже есть, но записан за другим сообщением.
			// Завести его второй раз нельзя (source_key неповторим), и до сих пор
			// он молча пропускался — а это и есть перевыкладка: автор удалил своё
			// сообщение и написал заново с тем же файлом. Запоминаем, где файл
			// лежит теперь; решать, переезд это или один документ, честно
			// висящий сразу в двух сообщениях, будет тот, кто прочитал тему
			// целиком (см. missingComments)
			if (knownDocument.get(document.key) !== undefined) {
				tally.moved.set(document.key, comment);
				continue;
			}

			const result = insertPackage.run(
				document.key,
				document.url,
				document.fileName,
				comment.topicUrl,
				comment.id,
				comment.author,
				comment.authorUrl,
				comment.date,
				// Через API время приходит числом, со страницы — строкой
				comment.ts ?? parseVkDate(comment.date),
				// Дата самого файла: со страницы её не узнать, и тогда null —
				// «неизвестно», а не «тогда же, когда сообщение» (см. contentTs)
				document.fileTs ?? null,
				comment.text,
			);

			if (result.changes > 0) {
				tally.added++;
			}
		}

		for (const row of missing) {
			if (row.status !== 'gone') {
				tally.pending.push({
					kind: 'gone',
					apply: () => markGone.run('файл убран из сообщения обсуждения', row.id),
					say: `файл убран: «${title(row)}»`,
				});
			}
		}
	}

	for (const document of documents) {
		const row = byKey.get(document.key);

		if (!row) {
			continue;
		}

		// Убранный файл вернули на место
		if (row.status === 'gone') {
			markBack.run(row.id);
			tally.back++;
			say('vk', `файл вернулся: «${title(row)}»`);
		}

		// Ссылки из API подписаны и живут недолго — обновляем на свежую
		if (useApi) {
			refreshLink.run(document.url, document.fileName, document.fileTs ?? null, document.key);
		}
	}

	const edited = rows.filter(row => (row.comment_text ?? '') !== comment.text);

	if (edited.length > 0) {
		const ts = comment.ts ?? parseVkDate(comment.date);

		for (const row of edited) {
			refreshComment.run(comment.text, comment.author, comment.authorUrl, comment.date, ts, row.id);
		}

		tally.edited++;
		say('vk', `сообщение переписано: «${title(edited[0])}»`);
	}
}

/**
 * Сообщения, которых в теме больше нет вовсе.
 *
 * ————— чего не видел прежний обход —————
 *
 * syncComment сверяет сообщение с тем, что о нём записано, и потому видит ровно
 * то, что ВК ему приносит, — а приносит он только сообщения с приложенными
 * файлами (см. buildComments в vkapi.js и parseComments в vk.js). Сообщение,
 * из которого убрали все файлы, и сообщение, удалённое целиком, до сверки
 * не доходили никогда, и «файл убран» у них не срабатывало ни разу. Так и вышло
 * в ночь на 21 августа 2026: обход прочитал все 26 289 сообщений темы, нашёл
 * 11 392 с файлами — и убрал ноль файлов, при том что паки из группы удаляли.
 * Пак, чьё сообщение стёрли, оставался на сайте живым навсегда, потому что
 * заметить его исчезновение было нечем.
 *
 * Теперь есть чем: обход отдельным потоком сообщает номера ВСЕХ прочитанных
 * сообщений (`onSeen`), и пак, номера которого среди них не оказалось, в теме
 * больше не лежит. Разница с syncComment только в том, что именно исчезло:
 * там — файл из сообщения, здесь — само сообщение; хоронятся оба одинаково
 * и одинаково же оживают, когда сообщение возвращают.
 *
 * ————— сообщение есть, а файла в нём нет —————
 *
 * Третий случай выглядит как ни один из двух. Автор правит сообщение и убирает
 * из него пак, оставив картинку и пару слов: так ушёл «кринж солянка №7» (21644)
 * 29 сентября 2026 — модераторы попросили переименовать темы, автор файл снял,
 * а сообщение 1102 осталось с одной фотографией. До syncComment оно доходит
 * (вложение-то есть), но там отсеивается сразу: .siq в нём нет, сверять нечего.
 * А здесь номер его среди прочитанных — и пак числился живым каждую ночь.
 *
 * Поэтому, кроме «прочитано», нужно ещё «прочитано и с паком» (`filed`): номер
 * из первого набора, которого нет во втором, — это сообщение без единого .siq,
 * и пак из него убран ровно так же, как если бы стёрли сообщение целиком.
 *
 * Спрашивать об этом вправе только полный обход темы. Хвост старой её части
 * не читал вовсе, оборванный обход не дочитал, перешагнутое окно унесло с собой
 * до сотни сообщений — для всех троих «сообщения нет» неотличимо от «мы туда
 * не дошли». Проверяет это зовущий (см. `whole` в scanVk), а сам приговор,
 * как и все прочие пропажи, копится до конца обхода и проходит через общий
 * предохранитель по числу (см. applyPending).
 *
 * @param {string} topicUrl тема, которую только что прочитали целиком
 * @param {Set<number>} seen номера сообщений, которые в ней нашлись
 * @param {Set<number>} filed из них — те, где приложен хотя бы один .siq
 *   (и те, что пропущены отсечкой темы: их не сверяли вовсе, и судить их не нам)
 * @param {object} tally общая копилка обхода
 */
function missingComments(topicUrl, seen, filed, tally) {
	const normalized = normalizeTopicUrl(topicUrl);

	for (const row of knownInTopic.all(normalized)) {
		// Пак, заведённый без номера сообщения, судить не по чему: его не было бы
		// среди прочитанных при любом исходе
		if (row.vk_comment === null || filed.has(row.vk_comment)) {
			continue;
		}

		// Сообщение на месте, но паков в нём не осталось ни одного
		const emptied = seen.has(row.vk_comment);

		const title = row.name ?? row.file_name ?? row.source_key;
		// Только внутри своей темы: файл, всплывший в другом обсуждении, — это
		// перевыкладка чужой рукой, и переселять туда строку вместе с оценками
		// и отметками «сыграно» не за что
		const found = tally.moved.get(row.source_key);
		const now = found?.topicUrl === normalized ? found : undefined;

		// Сообщения нет, а файл из него в теме есть — под другим номером. Это
		// не удаление, а перевыкладка, и хоронить тут нечего: пак переезжает
		// в новое сообщение вместе с его текстом и датой (см. rebindComment).
		//
		// Сомнений эта развилка не оставляет ровно потому, что спрашивают её
		// после полного обхода. Один и тот же документ и вправду бывает
		// приложен сразу к двум сообщениям — но тогда старое сообщение среди
		// прочитанных есть, и до этого места мы просто не доходим
		if (now !== undefined) {
			tally.pending.push({
				kind: 'moved',
				apply: () => rebindComment.run(now.id, now.author, now.authorUrl, now.date,
					now.ts ?? parseVkDate(now.date), now.text, row.id),
				say: `пак перевыложен другим сообщением: «${title}» — ${row.vk_comment} -> ${now.id}`,
			});
			continue;
		}

		tally.pending.push({
			kind: 'gone',
			apply: () => markGone.run(emptied
				? 'из сообщения обсуждения убраны все паки'
				: 'сообщение с паком удалено из обсуждения', row.id),
			say: emptied ? `из сообщения убраны все паки: «${title}»` : `сообщение удалено: «${title}»`,
		});
	}
}

/**
 * Пропажи и подмены не применяются сразу, а копятся до конца обхода — и здесь
 * решается, применять ли их вообще.
 *
 * Причина недоверия простая: и то, и другое опознаётся по отсутствию — файла,
 * который мы ожидали увидеть, в сообщении нет. Ровно так же выглядит день, когда
 * ВК поменял разметку страницы, или ключ перестал давать вложения, или обход
 * оборвался на середине. Разница в числе: люди правят сообщения по одному,
 * а сломавшийся обход «теряет» сразу сотни. Поэтому обвал считается поломкой
 * обхода, а не событием в обсуждении, и база остаётся вчерашней — из неё всегда
 * можно сделать сегодняшнюю, а вот обратно уже нет.
 */
function applyPending(pending, known) {
	if (pending.length === 0) {
		return { replaced: 0, gone: 0, moved: 0 };
	}

	const ceiling = Math.max(25, Math.round(known * 0.05));

	if (pending.length > ceiling) {
		console.error(`Обход насчитал ${pending.length} пропавших и подменённых файлов при ${known} паках в базе — `
			+ `это больше похоже на сломавшийся обход, чем на правки в обсуждении.`);
		console.error('Ничего не меняю. Если так и есть на самом деле, повторите запуск: порог считается от размера базы.');
		return { replaced: 0, gone: 0, moved: 0, refused: pending.length };
	}

	const counts = { replaced: 0, gone: 0, moved: 0 };

	for (const change of pending) {
		change.apply();
		counts[change.kind]++;
		say('vk', change.say);
	}

	return counts;
}

/**
 * Насколько раньше отсечки свежести начинать читать хвост темы, когда отметки
 * «докуда дочитали» ещё нет.
 *
 * Отсечка считается от нынешнего мига (`--fresh=1` — сутки назад), а пак попадает
 * в тему тогда, когда его выложили. Между тем и другим лежат все обычные
 * неурядицы: пропущенный по расписанию запуск, обход, отложенный очередью,
 * сообщение, у которого дата правки моложе даты выкладки. Лишние сутки хвоста
 * стоят одного-двух запросов к ВК, а сужать их до точности незачем: отбирает
 * свежие паки всё равно не обход, а условие по vk_ts (см. targetSql в src/indexer/queue.js).
 */
const TAIL_MARGIN_MS = 86_400_000;

/**
 * С какого мига читать хвост темы.
 *
 * Отметка «докуда дочитал прошлый такой обход» сильнее любого счёта от часов,
 * и в этом весь смысл ежечасного обхода: читать надо то, чего ещё не читали,
 * а не «последние двое суток» в тысячный раз. Пришёл обход через час — прочтёт
 * час; не приходил трое суток, потому что расписание GitHub пропустило запуски, —
 * прочтёт трое суток (см. src/indexer/tail.js).
 *
 * Отметки нет — считаем от часов, как раньше: так выглядит первый запуск
 * и база, приехавшая с полки постарше.
 *
 * Со свежестью работы это не путать. Здесь решается, сколько сообщений читать;
 * какие паки считать свежими для разбора и разметки, решает freshSince — и там
 * сутки остаются сутками, даже если хвоста прочитан час. Иначе пак, найденный
 * прошлым обходом и не доделанный им (кончилось время, кончилась квота),
 * выпал бы из работы насовсем: сообщение с ним прочитано, а значит, второй раз
 * прочитано не будет.
 */
const tailSince = () => tailReadUntil() ?? (freshSince - TAIL_MARGIN_MS);

export async function scanVk() {
	const useApi = hasVkApi();
	const startedAt = Date.now();

	// Хвостом читается тема тогда, когда об этом попросили ключом и когда есть
	// от чего считать хвост. Без ключа ВК так нельзя вовсе: разбор страниц темы
	// с конца читать не умеет
	const tailOnly = tail && useApi && freshSince !== null;
	const since = tailOnly ? tailSince() : null;
	const readTopic = !useApi
		? readTopicHtml
		: tailOnly
			? (url, options) => readTopicSince(url, since, options)
			: readTopicApi;

	say('vk', `обход обсуждений (${useApi ? 'через API' : 'разбором страниц, ключа нет'}`
		+ `${tailOnly ? `, только хвост — сообщения новее ${new Date(since).toLocaleString('ru-RU')}` : ''})`);

	const tally = { added: 0, edited: 0, back: 0, pending: [], moved: new Map() };
	const bar = track('vk');
	let comments = 0;
	let skipped = 0;
	let broken = 0;
	let unreadable = 0;
	let gaps = 0;

	for (const topic of config.vkTopics) {
		const topicUrl = topic.url;

		// Полночь по Москве: сама тема часового пояса не знает, а сообщения
		// сравниваются с отсечкой по фактическому моменту, а не по строке даты.
		const cutoff = topic.before ? Date.parse(`${topic.before}T00:00:00+03:00`) : null;

		say('vk', `тема ${topicUrl}${topic.before ? ` (паки до ${topic.before})` : ''}`);

		// Сколько сообщений в теме, ВК говорит в первом же ответе — по нему
		// и растёт полоска выполнения, а заодно видно, дочитали ли до конца
		let announced = null;
		let read = 0;

		// Номера всех сообщений темы, какие удалось прочитать, — вместе с теми,
		// где нет ни одного файла. По ним ниже разбирается, чьё сообщение
		// из обсуждения убрали (см. missingComments)
		const seenComments = new Set();
		// Из них — те, где лежит пак (см. «сообщение есть, а файла в нём нет»
		// у missingComments)
		const filedComments = new Set();
		let torn = false;
		const gapsBefore = gaps;
		const unreadableBefore = unreadable;

		try {
			for await (const comment of readTopic(topicUrl, {
				maxPages,
				onSeen: ids => {
					for (const id of ids) {
						seenComments.add(id);
					}
				},
				// Сообщение, на котором спотыкается сам ВК. Его пропускают, чтобы
				// прочитать всё остальное; пак под ним, если он там был, найдётся
				// только когда ВК починится (см. readWindow в vkapi.js)
				onSkip: at => {
					unreadable++;
					say('vk', `сообщение на месте ${at} прочитать нечем: ВК отвечает внутренней ошибкой. Иду дальше.`);
				},

				// Кусок темы, который ВК так и не отдал (пустой ответ и после
				// повторов). Тему это не обрывает — обход шагает дальше, — но
				// до сотни сообщений остались непрочитанными, и хоронить по такому
				// обходу пропавшие файлы нельзя: см. ниже, где считается applied.
				onGap: (at, size) => {
					gaps++;
					console.error(`[ВК] кусок темы с места ${at} (до ${size} сообщений) ВК не отдал даже после повторов. `
						+ 'Перешагиваю; непрочитанное подберётся следующим обходом.');
				},
				onPage: page => {
					// Сколько сообщений в теме, ВК называет сразу — с этого и растёт
					// полоска. Полоса обхода считает прочитанные сообщения, а не
					// найденные паки: паки попадаются далеко не в каждом сообщении,
					// и по ним не видно, много ли осталось.
					// Число это не каменное: пока идёт обход, в теме и пишут, и удаляют.
					// Берём всегда последнее сказанное, а полоску растим на разницу
					if (page.total !== null) {
						bar.expand(Math.max(0, page.total - (announced ?? 0)));
						announced = page.total;
					}

					bar.tick(Math.max(0, page.read - read));
					read = page.read;

					if (page.page % 25 === 0) {
						say('vk', `прочитано ${page.read}${page.total ? ` из ${page.total}` : ''} сообщений`
							+ `${bar.etaMs ? `, осталось ~${formatSpan(bar.etaMs)}` : ''}`);
					}
				},
			})) {
				comments++;

				if (cutoff !== null) {
					const ts = comment.ts ?? parseVkDate(comment.date);

					if (ts === null || ts >= cutoff) {
						// Не сверяли — значит, и не нам говорить, что пака там нет
						filedComments.add(comment.id);
						skipped++;
						continue;
					}
				}

				if (comment.documents.some(document => /\.siq$/i.test(document.fileName))) {
					filedComments.add(comment.id);
				}

				syncComment(comment, useApi, tally);
			}

			// Тему дочитали не до конца — и это не мелочь, а ровно тот случай,
			// из-за которого в базе не хватало семи тысяч паков: обход обрывался
			// на середине и молча объявлял, что всё собрано.
			//
			// Недобор в пару сообщений тревогой не считается: пока идёт обход,
			// в теме удаляют, и отсчёт под нами сдвигается сам собой. Страница —
			// та мера, ниже которой это точно не поломка.
			if (!tailOnly && announced !== null && announced - read > 100 && maxPages === Infinity) {
				broken++;
				torn = true;
				console.error(`[ВК] тема прочитана не до конца: ${read} сообщений из ${announced}. `
					+ 'Собранное осталось в базе, недочитанное подберётся следующим обходом.');
			}
		} catch (error) {
			broken++;
			torn = true;
			console.error(`[ВК] обход темы оборвался на ${read} сообщении: ${error.message}`);
			console.error('[ВК] Собранное до обрыва осталось в базе; остальное подберёт следующий обход.');
		}

		// Тема прочитана целиком — можно спросить, чьих сообщений в ней не стало.
		// Судит об этом только тот обход, который видел тему всю: у хвоста, у обхода
		// с оборванной темой, с перешагнутым окном и с сообщением, которое ВК
		// не отдал, «сообщения нет» и «до сообщения не дошли» выглядят одинаково.
		//
		// Нечитаемое сообщение стоит в этом ряду не для полноты: его номер
		// в прочитанные не попадает вовсе (см. readWindow в vkapi.js), и пак
		// под ним был бы похоронен ни за что.
		//
		// Отдельно — про `announced`. Это число сообщений в теме, названное самим
		// ВК, и приходит оно только через API. У разбора страниц его нет: там
		// признаком конца темы служит первая страница без сообщений, а такая
		// страница приходит и из середины темы. Обход, который не может отличить
		// конец темы от заминки на её середине, хоронить не вправе никого —
		// и без ключа ВК этот разбор просто не делается
		const whole = !torn && !tailOnly && maxPages === Infinity
			&& announced !== null && read >= announced
			&& gaps === gapsBefore && unreadable === unreadableBefore;

		if (whole) {
			missingComments(topicUrl, seenComments, filedComments, tally);
		}
	}

	const known = db.prepare('SELECT COUNT(*) AS c FROM packages').get().c;

	// Недочитанный обход не имеет права никого хоронить: «файла в сообщении нет»
	// и «до сообщения не дошли» выглядят одинаково, а разница в цене — целая база.
	//
	// Обход хвоста неполон всегда и по своему устройству: старой части темы он
	// не видел вовсе. Это не поломка, а его назначение — и потому он поставлен
	// сюда же, рядом с обрывом: судить о пропавших файлах ему нечем ровно так же
	const incomplete = broken > 0 || gaps > 0 || tailOnly;

	const applied = incomplete
		? { replaced: 0, gone: 0, moved: 0, refused: tally.pending.length }
		: applyPending(tally.pending, known);

	// Докуда дочитали. Двигает отметку только обход хвоста и только тогда, когда
	// прошёл целиком: сорвавшийся на середине или перешагнувший кусок темы
	// оставил бы за отметкой непрочитанное, и следующий обход туда уже не пошёл
	// бы никогда (см. src/indexer/tail.js).
	//
	// Сообщения, которых не отдал сам ВК (`unreadable`), отметке не мешают.
	// Такое сообщение не отдаётся и завтра, и послезавтра — держи мы из-за него
	// отметку на месте, ежечасный обход перестал бы двигаться вовсе.
	// Ограничение по числу окон (`--pages`) отметку тоже не двигает: такой обход
	// прочитал сколько велено, а не сколько надо, и до отсечки мог не дойти
	if (tailOnly && broken === 0 && gaps === 0 && maxPages === Infinity) {
		noteTailRead(startedAt);
	}

	if (incomplete && tally.pending.length > 0) {
		say('vk', `подмен и пропаж отложено: ${tally.pending.length}. `
			+ `${tailOnly ? 'Читался только хвост темы' : 'Обход был неполным'}, и верить им нельзя.`);
	}

	say('vk', `просмотрено сообщений с файлами: ${comments}`
		+ `${skipped ? ` (после отсечки не считали ${skipped})` : ''}. Новых паков: ${tally.added}.`
		+ `${unreadable ? ` Сообщений, которые ВК не отдал: ${unreadable}.` : ''}`
		+ `${gaps ? ` Кусков темы, которые ВК не отдал: ${gaps}.` : ''}`);
	say('vk', `изменений в прежних: файл заменён у ${applied.replaced}, `
		+ `перевыложено другим сообщением ${applied.moved}, `
		+ `переписано сообщений ${tally.edited}, убрано из обсуждения ${applied.gone}, вернулось ${tally.back}.`);

	if (broken > 0) {
		throw new Error(`обход не завершён: тем с обрывом — ${broken}`);
	}
}
