// Обход обсуждений ВК: что в теме появилось нового и что в старом изменилось.
//
// Единственный шаг, который заводит в базе строки; все прочие только дополняют
// то, что нашёл он. Отсюда и вторая его работа, не такая заметная: сверить
// уже известное сообщение с тем, что в нём лежит сейчас, — файл под сообщением
// подменяют, а сам пак при этом остаётся тем же местом в обсуждении.
//
// Он же обновляет ссылки на документы: они подписаны и живут недолго, поэтому
// в ночном порядке шагов он идёт первым (см. STEPS в steps.js).

