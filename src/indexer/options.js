// Ключи командной строки: всё, что сказано обходу при запуске.
//
// Разбираются один раз при загрузке и дальше только читаются — потому и живут
// отдельно от шагов. Спрашивают их все подряд: «этот пак вообще в очереди?»,
// «сколько работников?», «время не вышло?». Держи их в каком-нибудь одном
// шаге — и все остальные ходили бы к нему в гости за тем, что к нему
// не относится вовсе.
//
// Список ключей с объяснениями, что каждый делает, — в шапке src/indexer.js.

import { config } from '../config.js';
import { buildAuthorKey } from '../db.js';
import { useModel } from '../gemini/api.js';
import { say } from './progress.js';
import { tailReadUntil } from './tail.js';

const args = process.argv.slice(2);
export const has = flag => args.includes(flag);
export const text = name => args.find(a => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=') ?? '';
const value = (name, fallback) => {
	const found = text(name);
	return found ? Number(found) : fallback;
};

/**
 * «Переделать всё заново» одним ключом. Каждая из четырёх галочек существует
 * и по отдельности — обычный ночной обход ими и пользуется поодиночке, — а этот
 * ключ для другого случая: когда паки названы поимённо и переспрашивается всё,
 * что про них известно (см. --packs выше).
 */
export const force = has('--force');

export const reparse = has('--reparse') || force;
export const retopics = has('--retopics') || force;
export const resummary = has('--resummary') || force;
export const retryFailed = has('--retry') || force;

/**
 * `--reprints`: снять отпечатки вопросов заново по всей библиотеке, не спрашивая,
 * устарели ли они.
 *
 * Обычно шаг отпечатков сам знает, кого переснимать: пак без свёртки, пак,
 * разобранный после того, как её снимали, и пак со свёрткой прежнего вида —
 * вид записан рядом со свёрткой и сверяется с PRINTS_VERSION (см. fetchPrints
 * ниже). Пока правило меняли вместе с номером вида, этого хватало: подняли
 * номер — и вся библиотека сама встала в очередь.
 *
 * Не хватило в единственном, зато частом случае: правило поменяли, а номер
 * поднять забыли — или подняли, очередь прошла, и уже потом выяснилось, что
 * снималось не то. Тогда база стоит вся с нынешним номером и вся неправильная,
 * а переснять её нечем: `--force` работает только вместе с названными паками
 * (см. web/update.js), а называть поимённо одиннадцать тысяч штук никто не станет.
 * Ровно про это и спрашивали: «почему я не могу снять отпечатки заново, если
 * новая версия отпечатков реализована».
 *
 * Отсюда отдельный ключ. Он делает для отпечатков ровно то же, что `--reparse`
 * для разбора и `--retopics` для разметки: отменяет отбор «кому надо»
 * и переснимает всех подряд.
 */
export const reprints = has('--reprints') || force;

/**
 * `--refit`: сходить в ВК за теми обложками, чья уменьшенная копия лежит
 * не в том формате, под которым записана.
 *
 * Откуда берутся такие копии. ImageMagick шестой версии — тот, что стоит
 * на машине Actions, — AVIF читает, но не пишет: на просьбу сделать .avif
 * он кладёт исходный png или jpg под этим именем и выходит с нулём
 * (см. isAvif в src/thumbs.js). Копия на карточке показывается — браузер
 * нюхает первые байты и формату в имени не верит, — но весит вдвое с лишним
 * больше обещанного, а Content-Type под ней врёт. Так набралось 1942 файла
 * из 3111.
 *
 * Почему это ключ, а не всегдашнее поведение. Переделать такую копию можно
 * только из оригинала, а оригинал у 1749 из них не сохранился: наверх ездят
 * одни копии, оригиналы живут ровно столько, сколько живёт одноразовый раннер
 * (см. fetchLogo ниже). Значит, чинить их — это тысяча семьсот походов в ВК,
 * то есть отдельная работа на один раз, а не то, что ночь делает заодно.
 * Была бы она всегдашней — пак, чью обложку не берёт ни ImageMagick, ни ffmpeg,
 * качался бы заново каждую ночь до скончания века: `logo_state` у него остаётся
 * 'ok' (и обязан остаться — по нему обложка и показывается), а копия как
 * не подходила, так и не подходит.
 *
 * Новых таких копий больше не заводится: выкладка теперь смотрит внутрь файла,
 * а не на его время (см. scripts/build-web.js), и resizeInto спрашивает всех,
 * кто нашёлся, а не первого отозвавшегося. Этот ключ — про уже накопленное.
 *
 * Тот же ключ действует и на страницу «Обновить»: там он ничем не отличается
 * от `--logos`, только берёт ещё и тех, у кого копия не того формата.
 */
export const refit = has('--refit') || force;

export const upgrade = has('--upgrade');
export const serial = has('--serial');
export const maxPages = value('pages', Infinity);
export const limit = value('limit', Infinity);

/**
 * `--tail`: обойти не тему целиком, а только её хвост — сообщения, которых
 * прошлый такой обход ещё не читал (см. tailSince в src/indexer/vk-scan.js
 * и readTopicSince в src/vkapi.js).
 *
 * Отдельным ключом, а не само собой при `--fresh`, и это не мелочь. Обход темы
 * целиком делает две работы разом: находит новое и замечает, что в старом
 * сообщении подменили или убрали файл. Вторая работа возможна только у того,
 * кто прочитал тему до конца, — и делать её должен кто-то. Ночь читает всю тему
 * и делает обе; ежечасный обход берёт этот ключ и делает одну, зато за секунды
 * вместо десяти минут (см. .github/workflows/hourly.yml).
 */
export const tail = has('--tail');

/**
 * Сколько паков разбирать одновременно.
 *
 * Разбор пака — это не скачивание, а несколько коротких запросов вглубь архива:
 * оглавление, content.xml, логотип. Байт в них полторы сотни килобайт на пак,
 * но каждый поход к хранилищу ВК стоит от полусекунды до трёх секунд сам по себе,
 * сколько бы ни просили. Поэтому один пак в одиночку идёт секунд пять-десять,
 * и всё это время канал простаивает: ждём ответа, а не качаем.
 *
 * Отсюда и способ ускорения — не быстрее качать, а ждать нескольких сразу.
 * Замер на живых паках: десять хвостов подряд — 4.5 с на штуку, те же десять
 * разом — 0.96 с на штуку.
 */
export const jobs = Math.max(1, value('jobs', config.parseJobs));

/** Модель на этот запуск: --model= перебивает выбранную на странице обновления. */
if (text('model')) {
	useModel(text('model'));
}

/**
 * Разрешено ли посреди работы перейти на запасную модель, когда у нынешней
 * кончились суточные запросы (см. nextSpareModel в models.js).
 *
 * Ключом, а не всегда, потому что случая тут два разных. Ночной обход идёт сам,
 * смотреть за ним некому, и упереться в лимит на середине очереди для него —
 * обычное дело: там переход на соседнюю Lite означает несколько лишних тысяч
 * размеченных паков вместо «продолжим завтра». Запуск руками со страницы
 * обновления — другое: там модель выбрана человеком нарочно, и подменять её
 * молча нельзя, иначе выбор ничего не значит.
 *
 * Ключ ставит ночной обход сам (см. scripts/nightly.js).
 *
 * `--fallback=any` — то же самое, но выбирать не из запасных, а из всех моделей
 * подряд, начиная с самой мощной. Это ключ ежечасного обхода, и разница между
 * ним и обычным `--fallback` — в том, ради чего переключаются. Ночь меняет
 * модель ради очереди: ей важно, чтобы за оставшиеся часы разметилось побольше
 * паков, и старший Flash с двадцатью запросами в сутки для этого бесполезен.
 * Ежечасному обходу нужен один пак — тот самый, что появился в обсуждении час
 * назад, — и двадцати запросов ему хватает с лихвой. Оставить его до ночи
 * неразмеченным (карточка без типа, без описания, без сложности) хуже во всех
 * отношениях, чем разметить сильнейшей из живых (см. nextSpareModel в models.js).
 */
export const fallback = has('--fallback') || text('fallback') !== '';
export const fallbackAny = text('fallback') === 'any';

/**
 * Сколько минут работе отпущено. Ноль — сколько угодно, как было всегда.
 *
 * Это не ограничение ради ограничения, а способ доделать работу до конца.
 * Обход не кончается сам: очередь в базе на тысячи паков, а размечается она
 * сотнями, и всякий полный проход упирается либо в лимиты Gemini, либо в чужое
 * терпение. В облаке терпение измеримо — GitHub убивает работу на шести часах,
 * и убивает грубо: не «доделай и выйди», а обрыв посреди запроса. Дальше
 * не выполняется ничего: ни выкладка, ни отчёт. Две ночи подряд (16 и 17 августа
 * 2026) так и прошли — по пять с лишним часов разметки, около двух тысяч
 * размеченных паков за ночь, и ни один из них не доехал до сайта, потому что
 * шаг выкладки стоит ПОСЛЕ обхода, а до него дело не дошло.
 *
 * Срок решает это целиком. Индексатор смотрит на часы там же, где смотрит
 * на кончившиеся лимиты (см. drain в src/indexer/pipeline.js), и по истечении времени доводит начатое
 * до конца и выходит с успехом — а ночь спокойно идёт дальше, к выкладке.
 * Сделано меньше, зато сделанное — на сайте.
 */
const minutesLeft = value('minutes', 0);
const finishBy = minutesLeft > 0 ? Date.now() + minutesLeft * 60_000 : null;

/** Кончилось ли отпущенное время. Проверяется на каждом круге очереди. */
let timeUp = false;

export function outOfTime() {
	if (!finishBy || timeUp) {
		return timeUp;
	}

	if (Date.now() >= finishBy) {
		timeUp = true;
		say('time', `отпущенные ${minutesLeft} мин вышли: доделываю начатое и заканчиваю. `
			+ 'Оставшаяся очередь никуда не денется — её возьмёт следующий обход.');
	}

	return timeUp;
}

/**
 * Паки, названные поимённо: `--packs=128,340`. Номер — тот же, что в адресе
 * страницы пака (/pack/128-...), поэтому ссылку можно просто вставить целиком:
 * всё, что не число, отсеивается.
 */
export const onlyPacks = text('packs')
	.split(/[^0-9]+/)
	.map(part => Number.parseInt(part, 10))
	.filter(id => Number.isFinite(id) && id > 0);

/**
 * Авторы, чьи паки разбираются.
 *
 * Их два списка, и делают они разное. `--authors=Имя,Имя` — разовый: очередь
 * состоит только из паков этих авторов, всё остальное шаг не трогает вовсе.
 * `config.priorityAuthors` — постоянный: очередь остаётся полной, но паки
 * перечисленных авторов встают в её начало. Нужны оба: первым догоняют одного
 * автора здесь и сейчас, вторым решают, кем каждую ночь начинать.
 *
 * Имена сводятся к ключу тем же правилом, что и в таблице pack_authors, —
 * иначе «Кот» и «кот» оказались бы разными людьми.
 */
export const onlyAuthors = text('authors').split(',').map(name => buildAuthorKey(name)).filter(Boolean);
export const priorityAuthors = (config.priorityAuthors ?? []).map(name => buildAuthorKey(name)).filter(Boolean);

/** Названы ли паки поимённо. От этого зависит, что вообще делать в этот запуск. */
export const targeted = onlyPacks.length > 0 || onlyAuthors.length > 0;

/**
 * Только недавно выложенное: `--fresh=3` — паки, появившиеся в обсуждении
 * за последние трое суток.
 *
 * Ради ночного обхода (см. scripts/nightly.js). Ночь идёт двумя проходами:
 * сперва короткий — обойти обсуждения и разобрать всеми средствами то, что
 * выложили на днях, — и лишь потом длинный, по всей остальной базе. Разница
 * не в объёме работы, а в том, что случится, когда её прервут: суточный лимит
 * Gemini кончается посреди ночи всегда, и без этого прохода сегодняшний пак мог
 * упереться в него наравне с трёхлетним. Теперь свежее сделано ещё до того, как
 * начато остальное.
 *
 * От `--packs` отличается тем, что не отменяет обход ВК: новые паки в базе
 * берутся именно оттуда, и в первом проходе обход и есть главное.
 *
 * Свежесть меряется по дате сообщения (vk_ts), а не по времени попадания в базу:
 * пак, найденный сегодня в старой теме, новым не является — он просто не попадался
 * раньше, и разбирать его вне очереди незачем.
 */
export const freshDays = value('fresh', 0);

/**
 * Миг, раньше которого пак не считается свежим.
 *
 * Это отсечка работы, а не чтения: по ней шаги отбирают, с какими паками
 * возиться (см. targetSql в src/indexer/queue.js). Сколько сообщений читать
 * в обсуждении — вопрос отдельный, и у ежечасного обхода на него отвечает
 * отметка «докуда дочитали» (см. tailSince в src/indexer/vk-scan.js).
 *
 * Обычно это просто «столько-то суток назад». Но у обхода хвоста есть вторая
 * мерка, и в одну сторону она сильнее: если прошлый такой обход был давно —
 * расписание GitHub пропустило запуски, — то читать он будет всё пропущенное,
 * и паки оттуда обязаны попасть в работу. Иначе вышло бы худшее из двух:
 * обход нашёл бы пак трёхдневной давности, завёл бы его строкой в базе,
 * а разбор и разметка до него бы не дошли — для них свежее это сутки.
 *
 * Сузить отсечку отметка не может никогда, и это важнее, чем кажется. Обход,
 * пришедший через час после предыдущего, всё равно считает свежим выложенное
 * за сутки — потому что в работе остаётся не только найденное сейчас, но и всё
 * недоделанное прошлыми запусками: у них кончалось время посреди очереди
 * или кончалась суточная квота Gemini. Сообщения с этими паками давно
 * прочитаны и второй раз прочитаны не будут; единственное, что держит их
 * в работе, — вот эта суточная отсечка.
 */
const askedSince = freshDays > 0 ? Date.now() - freshDays * 86_400_000 : null;
const readUntil = tail ? tailReadUntil() : null;

export const freshSince = askedSince === null
	? null
	: (readUntil === null ? askedSince : Math.min(askedSince, readUntil));
