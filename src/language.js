// Язык пака по письму его тем.
//
// ————— зачем это понадобилось —————
//
// Язык паку называет модель (см. LANGUAGE_RULES в src/gemini/summary.js),
// и одно место она путает раз за разом: музыкальный пак, где все ответы —
// названия западных песен. «Led Zeppelin — Immigrant Song», «Taylor Swift —
// Our Song», сотня таких подряд, — и ответ приходит «en», хотя разговаривают
// в этом паке по-русски: темы называются «"Дверные" Песни» и «Ни один Райан
// Гослинг не пострадал в конце этих песен».
//
// Правило про это в запросе есть и написано прямо («название произведения
// языком пака НЕ является»), но запрос — не проверка: модель ему то следует,
// то нет, а пак на сайте после этого числится английским и пропадает из выдачи
// у тех, кто отбирает русские паки.
//
// Здесь — то же самое правило, только считаемое, а не выпрашиваемое: у тем
// пака есть письмо, и оно видно из строки. Темы кириллицей — значит, пак
// не английский, что бы ни было написано в ответах.
//
// ————— почему только в одну сторону —————
//
// Латинская подпись кириллического пака — ошибка; кириллическая подпись
// латинского — нет. Пак с темами на английском, но с ответами по-русски
// («Кто написал "Войну и мир"?») остаётся русским: разговаривают в нём
// по-русски, а тема — это заголовок из пяти слов, который автор вполне мог
// назвать «Rock Music» из красоты. Поэтому здесь отменяется только латинский
// приговор и никогда — кириллический.
//
// ————— чистый файл —————
//
// Ни node:, ни базы: на вход строки, на выходе код языка. Считают по нему
// двое — запись ответа модели (см. saveSummary в src/indexer/store.js)
// и пересчёт по уже сохранённому (см. recalcLanguages в src/indexer/recalc.js),
// — и правило это обязано быть у обоих одно.

/** Языки сайта, которые пишутся кириллицей. Приговор из этого списка не трогается. */
export const CYRILLIC_LANGS = ['ru', 'uk', 'be', 'kk'];

const CYRILLIC = /[Ѐ-ӿ]/;
const LETTER = /[Ѐ-ӿA-Za-z]/;

/**
 * С какой доли тем, написанных кириллицей, пак перестаёт быть латинским.
 *
 * Половина, а не «хоть одна» и не «все». «Хоть одна» сработала бы на настоящем
 * английском паке, где одна тема названа по-русски шутки ради. «Все» не сработали
 * бы почти нигде: в русском музыкальном паке одна-две темы сплошь из имён
 * («Faves», «Queen & Co»), и письма у них нет вовсе.
 *
 * Темы без букв — из цифр, знаков и смайликов — в доле не участвуют ни с той,
 * ни с другой стороны: сказать о языке им нечем.
 */
export const CYRILLIC_THEMES = 0.5;

/** Двухбуквенный код из того, что записано в файле или названо моделью: «ru-RU» → «ru». */
export const langKey = value => String(value ?? '').trim().toLowerCase().slice(0, 2);

/** Названия тем пака — все, из всех раундов. */
export function themeNames(rounds) {
	return (Array.isArray(rounds) ? rounds : [])
		.flatMap(round => (Array.isArray(round?.themes) ? round.themes : []))
		.map(theme => String(theme?.name ?? ''));
}

/**
 * Доля тем, написанных кириллицей, среди тех, в которых вообще есть буквы.
 *
 * Тема считается кириллической, если в ней есть хоть одна кириллическая буква:
 * «Песни Nirvana» — русская тема с именем собственным внутри, и таких
 * в музыкальных паках больше половины.
 *
 * @returns {number|null} null — тем нет вовсе или ни в одной нет букв
 */
export function cyrillicThemeShare(rounds) {
	const named = themeNames(rounds).filter(name => LETTER.test(name));

	if (named.length === 0) {
		return null;
	}

	return named.filter(name => CYRILLIC.test(name)).length / named.length;
}

/**
 * Приговор о языке, проверенный письмом тем.
 *
 * ————— когда темам сказать нечего —————
 *
 * Темы вида «1», «2», «3» и «a», «b», «c» — не редкость: так подписывают
 * музыкальные паки и паки по постерам, где заголовок темы выдал бы ответ.
 * Письма у таких тем нет вовсе, и судить по ним не о чем — тогда за них
 * отвечает название самого пака: «Кинопак № 18» с темами «1 / 2 / 3» написан
 * по-русски, и другого места, где это видно, у него нет.
 *
 * Название стоит именно ЗАПАСНЫМ, а не наравне с темами: русский пак вполне
 * называют «Impossible Musical Challenge», а вот темами по-русски подписывают
 * только русский пак.
 *
 * @param {string} language что назвали языком пака — модель или файл
 * @param {string} fromFile что записано в самом паке: им и заменяется отменённый
 *   приговор, если он кириллический. «en-US» в файле при русских темах — тот же
 *   самый промах редактора, ради которого модель и спрашивают, и опираться
 *   на него нельзя; тогда остаётся «ru» — язык, на котором написаны почти все
 *   паки «Своей игры»
 * @param {Array} rounds разобранные раунды пака
 * @param {string} [name] название пака — на случай, если в темах нет ни буквы
 * @returns {string} код языка: тот же или кириллический
 */
export function languageByThemes(language, fromFile, rounds, name = '') {
	const said = langKey(language);

	if (!said || CYRILLIC_LANGS.includes(said)) {
		return said;
	}

	const share = cyrillicThemeShare(rounds);
	const written = share === null
		? (LETTER.test(String(name ?? '')) ? Number(CYRILLIC.test(String(name))) : null)
		: share;

	if (written === null || written < CYRILLIC_THEMES) {
		return said;
	}

	const own = langKey(fromFile);

	return CYRILLIC_LANGS.includes(own) ? own : 'ru';
}
