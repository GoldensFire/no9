// Как пак опознаётся и как читаются его поля.
//
// Вынесено из db.js по той же причине, что и settings.js из config.js: db.js
// открывает файл базы через node:sqlite, а на Cloudflare Workers ни файлов,
// ни node:sqlite нет — там та же база лежит в D1 (см. cf/). Ключи же обязаны
// считаться одинаково с обеих сторон: разойдись они, и оценка, поставленная
// на сайте, перестала бы находить свой пак.
//
// db.js всё это перевыпускает наружу, поэтому в самом проекте ничего
// не изменилось: как импортировали packKey из db.js, так и импортируем.

export function jsonOrDefault(value, fallback) {
	if (value === null || value === undefined) {
		return fallback;
	}

	try {
		return JSON.parse(value);
	} catch {
		return fallback;
	}
}

/**
 * Раунды из базы в едином виде. Старые записи хранят темы строками,
 * новые — объектами с числом вопросов и образцом ответов.
 */
export function normalizeRounds(value) {
	return jsonOrDefault(value, []).map(round => ({
		name: round.name ?? '',
		type: round.type ?? '',
		themes: (round.themes ?? []).map(theme => typeof theme === 'string'
			? { name: theme, questions: 0, sample: '' }
			: { name: theme.name ?? '', questions: theme.questions ?? 0, sample: theme.sample ?? '' }),
	}));
}

/**
 * Раунды для сайта: только название раунда и названия тем — ровно то, что
 * карточка показывает в «Подробнее».
 *
 * Отдельно от normalizeRounds ради веса ответа. В базе у каждой темы лежит ещё
 * и образец её содержимого (`sample`) — выжимка ответов и кусков вопросов, ради
 * которой всё и затевалось: по ней модель размечает тематики и пишет краткое
 * описание (см. buildSample в src/siq.js). Показывать его негде и не за чем,
 * а весит он на страницу в две дюжины паков 126 КБ из 273 КБ всего ответа —
 * то есть почти половину выдачи браузер получал ради поля, которое ни одна
 * строчка сайта не читает. Число вопросов темы и вид раунда сайт не читает тоже.
 *
 * Индексатору и разметке достаётся полный вид: они ходят в базу, а не сюда.
 *
 * Сквозь этот отбор проезжает кроме названия только то, что про плагиат,
 * и обеими его сторонами сразу (см. src/plagiarism.js).
 *
 * Взято этим паком: `src` — номер пака, в котором вопросы этой темы стояли
 * раньше, `n` — сколько их оттуда, `of` — сколько вопросов в теме всего,
 * `srcs` — все доноры темы с именами, когда их больше одного. Числа тут стоят
 * того: без них карточка не отличила бы тему, взятую целиком, от темы,
 * из которой списали один вопрос, — и обвиняла бы обе одинаково; а без списка
 * доноров подсказка называла бы один пак там, где их три.
 *
 * Взято у этого пака: `taken` — кто позже поставил вопросы этой темы себе,
 * с именами и числами, и `takenOf` — сколько вопросов в теме всего. Это
 * не обвинение паку, а обратное ему: такая тема красится зелёным.
 *
 * Образец при этом остаётся дома по-прежнему — он и есть то тяжёлое, ради чего
 * этот отбор написан.
 */
export function roundsForApi(value) {
	return jsonOrDefault(value, []).map(round => ({
		name: round.name ?? '',
		themes: (round.themes ?? []).map(theme => {
			if (typeof theme === 'string') {
				return { name: theme };
			}

			const out = { name: theme.name ?? '' };

			if (theme.src) {
				out.src = theme.src;
				out.n = theme.srcN ?? 0;
				out.of = theme.srcOf ?? 0;

				if (theme.srcs) {
					out.srcs = theme.srcs;
				}
			}

			if (theme.taken) {
				out.taken = theme.taken;
				out.takenOf = theme.takenOf ?? 0;
			}

			return out;
		}),
	}));
}

/**
 * Кто автор пака, когда в самом паке этого не написано.
 *
 * Поле <author> в .siq заполняет человек руками, и заполняет далеко не всякий:
 * полсотни паков библиотеки подписаны пустым тегом («<author />») или
 * не подписаны вовсе. На сайте такой пак стоял вообще без автора — ни строки
 * под названием, ни ссылки на страницу человека, ни места в топе авторов, —
 * при том, что кто его выложил, известно совершенно точно.
 *
 * Известно оттуда же, откуда взялся сам пак: из сообщения в обсуждении ВК.
 * Подпись под сообщением — это имя и фамилия со страницы (vk_author), и она
 * ничем не хуже ника: паки того же человека, подписанные внутри файла, сведёт
 * с ней слияние авторов — оно как раз и связывает разные написания по общей
 * странице ВК (см. mergeAuthors в src/indexer/authors.js).
 *
 * Берётся она только в пустоту и никогда поверх: пак, подписанный автором,
 * остаётся подписанным так, как подписал автор, даже если выложил его кто-то
 * другой. Перевыложенный чужой пак иначе достался бы перевыкладывающему.
 */
export function authorsOrVk(authors, vkAuthor) {
	const named = (authors ?? []).map(item => String(item ?? '').trim()).filter(Boolean);

	if (named.length > 0) {
		return named;
	}

	const fallback = String(vkAuthor ?? '').trim();

	return fallback ? [fallback] : [];
}

/** Ключ, по которому пак ищется в сервисе статистики: имя + авторы. */
export function buildMatchKey(name, authors) {
	const normalizedName = (name ?? '').trim().toLowerCase();
	const normalizedAuthors = (authors ?? []).map(a => a.trim().toLowerCase()).join(',');
	return `${normalizedName}\n${normalizedAuthors}`;
}

/**
 * Сколько игр приходится на один пак, когда сервис статистики посчитал их
 * на несколько паков сразу.
 *
 * Сервис SIGame ищет пак по имени и авторам из файла — ровно по тому, из чего
 * складывается buildMatchKey выше, — и другого ключа у него нет. Пока автор
 * называет свои паки по-разному, всё честно. Но многие не называют: у МакКайлы
 * четырнадцать паков, и все четырнадцать — «Вопросы SIGame»; у автора
 * «Different» таких двадцать два. Сервис складывает их игры в одну кучу
 * и отвечает одним и тем же числом на все четырнадцать вопросов.
 *
 * Раньше это число так и стояло на каждой из четырнадцати карточек, а рядом
 * с ним — звёздочка «это на всех сразу». Читалось оно всё равно как правда
 * о каждом: «1645 игр» подряд на четырнадцати паках выглядит четырнадцатью
 * популярными паками, а не одним. Поэтому куча делится поровну — это тоже
 * не точный ответ (разделить её по-настоящему нечем, она сложена не у нас),
 * но ошибается он в единственно допустимую сторону: суммы по автору и по
 * библиотеке от такого деления сходятся, а от повтора — нет.
 *
 * Проценты (правильных, отвечавших) и уровень сложности деления не требуют:
 * они и так доли, а не суммы.
 *
 * @param {number} total что ответил сервис
 * @param {number} twins на скольких паков разом это посчитано
 */
export function perPackGames(total, twins) {
	const count = Math.max(1, Math.trunc(Number(twins) || 1));

	return count > 1 ? Math.round((total ?? 0) / count) : (total ?? 0);
}

/** Одно написание автора для сравнения: регистр, ё и лишние пробелы не важны. */
export function buildAuthorKey(author) {
	return author.trim().toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

// ————— составные подписи —————
//
// В поле <author> внутри пака нередко записаны сразу несколько человек, и записаны
// как придётся: «Vieldy,Pa4ok,Slime», «r1v1_666 & Wiqox & adderall», «vadim и
// бурмалда», «Бурмалда, drugs (аптека)». Для базы это была одна подпись целиком:
// нажать на неё можно было только вместе, паки Бурмалды по такой строке
// не находились, а в топе авторов каждое такое сочетание стояло отдельным
// «автором» — при том, что все его паки уже посчитаны каждому из них порознь.
//
// Разбор нарочно осторожный: где непонятно, строка остаётся целой. Лишний
// несуществующий автор в списке хуже, чем неразобранная подпись, — его паки
// потеряются, а вторую половину подписи потом не найти.

/**
 * Части, которые именем не являются: так подписывают «и все остальные».
 * Сравниваются по buildAuthorKey, поэтому пишутся здесь в нижнем регистре.
 */
const NOT_AUTHORS = new Set([
	'др', 'и др', 'другие', 'и другие', 'прочие', 'остальные', 'все',
	'etc', 'co', 'ко', 'feat', 'ft', 'и', 'and', 'хз', 'люди', 'др.',
]);

/**
 * Похоже на ссылку, а не на подпись. Такие строки не режем вовсе: косые черты
 * и точки в адресе — часть адреса, и «https://vk.com/narygrown» превратилось бы
 * в двух авторов «https:» и «vk.com».
 */
const LOOKS_LIKE_LINK = /https?:\/\/|www\.|\b[a-z0-9-]+\.(?:com|ru|tv|me|to|org|net|io)\b/i;

/**
 * Разделители перечисления. Косая черта — только с пробелами вокруг: «Tw/LastGoMer»
 * и «B()tYaR/\3I» это цельные прозвища, а «sentsuri / 86» — двое.
 *
 * Флаг y (липучий) нужен, чтобы спрашивать «стоит ли разделитель ровно здесь»,
 * а не «есть ли он где-нибудь дальше».
 */
const SEPARATORS = /\s*[,;&+]\s*|\s+\/\s+/y;

/** Союз между двумя подписями. Тоже липучий и по той же причине. */
const AND_WORD = /\s+(?:и|and)\s+/iy;

/** Сколько слов в части. По ним решается, перечисление ли это через «и». */
const wordCount = text => text.split(/\s+/).filter(Boolean).length;

/**
 * Режет по разделителям верхнего уровня: то, что в скобках, остаётся целым.
 * «bbonbon8(1-й раунд), h0b0t(2,3 раунд)» — двое, а не четверо.
 */
function splitTopLevel(text) {
	const parts = [];
	let depth = 0;
	let start = 0;

	for (let i = 0; i < text.length; i++) {
		const char = text[i];

		if (char === '(' || char === '[') {
			depth++;
			continue;
		}

		if (char === ')' || char === ']') {
			depth = Math.max(0, depth - 1);
			continue;
		}

		if (depth > 0) {
			continue;
		}

		SEPARATORS.lastIndex = i;

		if (SEPARATORS.test(text)) {
			parts.push(text.slice(start, i));
			start = SEPARATORS.lastIndex;
			i = start - 1;
		}
	}

	parts.push(text.slice(start));
	return parts;
}

/**
 * «Лиса и Помидор» — двое, а «Господи ну и дурак этот Кубик» — один. Отличаются
 * они длиной сторон: перечисляют прозвищами, а не предложениями, поэтому режем
 * только когда с обеих сторон стоит не больше двух слов.
 */
function splitByAnd(text) {
	for (let i = 0; i < text.length; i++) {
		AND_WORD.lastIndex = i;

		if (!AND_WORD.test(text)) {
			continue;
		}

		const left = text.slice(0, i).trim();
		const right = text.slice(AND_WORD.lastIndex).trim();

		if (!left || !right || wordCount(left) > 2 || wordCount(right) > 2) {
			continue;
		}

		return [left, right];
	}

	return [text];
}

/**
 * Подписи паков по одному человеку. Ничего не находит — возвращает то, что было:
 * потерять автора хуже, чем оставить составную подпись неразобранной.
 *
 * @param {string[]} authors как записано в самом файле пака
 * @returns {string[]} по имени в строке, без повторов
 */
export function splitAuthors(authors) {
	const out = [];
	const seen = new Set();

	for (const raw of authors ?? []) {
		const text = String(raw ?? '').trim();

		if (!text) {
			continue;
		}

		const pieces = LOOKS_LIKE_LINK.test(text)
			? [text]
			: splitTopLevel(text).flatMap(splitByAnd);

		for (const piece of pieces) {
			// Хвостовые точки и многоточия к имени не относятся: «NSPants и др.»
			const name = piece.trim().replace(/[.,;\s]+$/u, '').trim();
			const key = buildAuthorKey(name);

			if (!key || NOT_AUTHORS.has(key) || seen.has(key)) {
				continue;
			}

			seen.add(key);
			out.push(name);
		}
	}

	// Разобрали в ноль (подпись была из одних «и др.») — пусть остаётся как есть
	return out.length > 0 ? out : (authors ?? []).map(a => String(a).trim()).filter(Boolean);
}

/**
 * Подписи пака — по людям, а не по написаниям.
 *
 * Разные написания одного человека сведены в базе к одному канону (см.
 * mergeAuthors в src/indexer/authors.js), и на карточке человеку показывается
 * канон — имя, под которым его знают. Написаний при этом бывает много, и до
 * сих пор каждое из них выводило по строке: пак 19601 («Одиссея по
 * гипоталамусу») подписан двадцатью шутками — «Стивен Хокинг», «Святой Дух»,
 * «Губка Боб Квадратные Штаны», — все двадцать сведены к teraaakot, и под
 * заголовком стояло «teraaakot» двадцать раз подряд. В описании для поисковика
 * оно же — двадцать раз через запятую, до обрезки по длине.
 *
 * Поэтому человек в списке остаётся один, первым своим написанием. Остальные
 * его написания не теряются, а едут при нём (keys): по ним стоит галочка
 * автора и узнаётся свой пак, и потеряй их — подтверждённый автор, подписавший
 * файл вторым своим ником, остался бы без галочки.
 *
 * @param {string[]} written подписи из файла, уже разобранные (см. splitAuthors)
 * @param {Map<string, {name?: string, slug?: string}>} counts готовый счёт паков
 *   по подписям: из него берутся канон-имя и кусок адреса страницы автора
 * @returns {Array<{key: string, name: string, keys: string[]}>} по человеку
 *   в строке: ключ первого написания, показываемое имя и все его написания
 */
export function mergeWrittenAuthors(written, counts) {
	const people = [];
	const at = new Map();

	for (const author of written ?? []) {
		const key = buildAuthorKey(author);
		const found = counts?.get(key);
		const name = found?.name || author;
		// Один человек — это либо одна страница автора, либо одно показываемое
		// имя. Кусок адреса надёжнее: имена «Кот» и «кот» на странице одни и те
		// же, а вот у автора без своей страницы его нет вовсе, и тогда сверяются
		// имена — тем же правилом, каким считается ключ подписи
		const mark = found?.slug || buildAuthorKey(name) || key;
		const same = at.get(mark);

		if (same) {
			same.keys.push(key);
			continue;
		}

		const person = { key, name, keys: [key] };
		at.set(mark, person);
		people.push(person);
	}

	return people;
}

/**
 * Ключ пака, общий для всех его копий: один и тот же файл нередко выложен
 * в обсуждение не по разу, и всё, что человек про пак говорит, — отметка
 * «сыграно», оценка, чёрный список — относится к паку, а не к строке в базе.
 *
 * Ключ — это номер оставшегося пака: свой собственный у того, кто копией
 * не является, и номер старшего у того, кто ею признан (см. markCopies
 * в src/indexer/copies.js). Копии на сайте не показываются вовсе, а оценка, поставленная
 * копии до того, как её признали копией, по этому ключу переезжает на оставшийся.
 *
 * ————— почему не идентификатор из файла —————
 *
 * Раньше ключ складывался из идентификатора пака и его названия. Рассуждение
 * было такое: идентификатор автор уносит с собой, делая новый пак из старого
 * файла, поэтому одного его мало, — а вот идентификатор вместе с названием
 * разные паки различает, потому что «Аниме пак № 5» и «№ 6» названы по-разному.
 *
 * Правило это держалось на том, что автор даёт своим пакам разные названия.
 * А он не даёт. У МакКайлы четырнадцать паков, и все четырнадцать называются
 * «Вопросы SIGame» при одном и том же идентификаторе внутри; у автора
 * «Different» таких двадцать два, у «mazefaka» девять. Ключ выходил один
 * на всех, и последствия шли по всему сайту: на странице автора вместо
 * четырнадцати паков стоял один — там они считаются по разным ключам, — отметка
 * «сыграно» на одном зажигалась на всех, оценка одному ставилась всем. Паков,
 * слипшихся так, в базе полтысячи.
 *
 * Между тем ответ на вопрос «один это пак или разные» в базе уже есть, и он
 * куда лучше: его считает шаг «Спрятать копии паков». Копией он признаёт пак,
 * у которого с соседом сошлись автор, название, вес архива и сами вопросы
 * с ответами — по отпечаткам, вопрос за вопросом. Четырнадцать паков МакКайлы
 * ни одной такой парой не оказались, и правильно: у них и вопросов разное
 * число, и архивы расходятся на десятки мегабайт.
 *
 * Поэтому ключ теперь и есть этот ответ. Пока шаг копий не проходил, copy_of
 * пуст, и каждый пак сам себе ключ — ровно то, что раньше делала запасная ветка
 * «идентификатора нет, бери номер строки».
 *
 * SQL-двойник строкой ниже; менять их нужно вместе.
 */
export function packKey(row) {
	return String(row.copy_of ?? row.id);
}

const packKeySql = prefix => `CAST(COALESCE(${prefix}copy_of, ${prefix}id) AS TEXT)`;

export const PACK_KEY_SQL = packKeySql('p.');

/**
 * Тот же ключ без имени таблицы — таким его записывают в указатель.
 *
 * Указатель по выражению SQLite заводит только на колонках самой таблицы,
 * без всяких «p.», а вот в запросе то же выражение стоит уже с именем: разбор
 * запроса сводит одно к другому, и указатель находится. Записаны они всё-таки
 * порознь, потому что порознь и читаются: одно — база, другое — запрос.
 */
export const PACK_KEY_INDEX_SQL = packKeySql('');

/**
 * Ключ названия со стороны базы — та половина match_key, что лежит до перевода
 * строки, то есть уже приведённое к нижнему регистру название пака
 * (см. buildMatchKey выше). По нему опознаётся список паков, принесённый
 * файлом: «вот двести названий, что из них есть в базе».
 *
 * Отдельной колонки под него нет и не надо. На стороне JS ту же половину
 * считает свой nameKey (см. src/packlist.js) — и считает там, а не в SQL,
 * нарочно: LOWER() в SQLite умеет только латиницу, и русские названия в базе
 * и в файле разошлись бы.
 *
 * Двойник без имени таблицы — рядом и по той же причине, что у ключа пака:
 * указатель по выражению SQLite заводит только на колонках самой таблицы,
 * без всяких «p.», а в запросе то же выражение стоит уже с именем
 * (см. ix_packages_name_key в src/db.js).
 */
const nameKeySql = prefix => `SUBSTR(${prefix}match_key, 1, INSTR(${prefix}match_key, CHAR(10)) - 1)`;

export const NAME_KEY_SQL = nameKeySql('p.');

export const NAME_KEY_INDEX_SQL = nameKeySql('');

/**
 * Написание подписи, под которым человека знают, — то, которым подписано
 * больше всего его паков.
 *
 * Зачем это отдельно от canon_name в базе. Столбец этот проставляет ночной
 * обход (см. mergeAuthors в src/indexer/authors.js), а на карточке пака до сих
 * пор стояло не оно, а подпись из файла КОНКРЕТНОГО пака — то, что автор
 * написал в поле <author> вот этой одной «Кринж солянки». Человек подписывается
 * то так, то этак, и выходило, что на карточке стоит «baziltred», а страница
 * автора, куда эта же подпись ведёт, называется «петя»: одно имя ведёт
 * на другое, и понять, тот ли это человек, было не по чему.
 *
 * Считается по человеку (canon_key), а не по подписи: все написания одного
 * человека сводит обход, и главное из них — общее на всех. Порядок при
 * равенстве тот же, что и у самого обхода: короче, а потом по алфавиту, —
 * иначе имя плясало бы от заливки к заливке.
 *
 * Живут паки только со status = 'ok': мёртвые и снятые с публикации имени
 * не выбирают. Кусок запроса, а не функция, потому что спрашивают его трое —
 * домашний сайт, сборка статики и Worker, — и разойтись им нельзя.
 */
export const AUTHOR_NAME_SQL = `
	SELECT k, name FROM (
		SELECT a.canon_key AS k, a.author AS name,
			ROW_NUMBER() OVER (
				PARTITION BY a.canon_key
				ORDER BY COUNT(*) DESC, LENGTH(a.author) ASC, a.author ASC
			) AS rn
		FROM pack_authors a JOIN packages p ON p.id = a.package_id
		WHERE p.status = 'ok'
		GROUP BY a.canon_key, a.author
	) WHERE rn = 1
`;

/**
 * Какая часть вопросов пака приходится на повторы франшиз — тем же счётом,
 * каким это число выводит карточка (см. createFranchises в web/card-parts.js).
 *
 * Лежит готовым числом в колонке packages.repeat_share: считать его на лету
 * из сохранённого JSON выходит слишком дорого. Обход json_each по всей таблице
 * стоит четверть секунды, а колонка фильтров спрашивает его пять раз кряду —
 * полторы секунды на одно нажатие галочки, и это дома; наверху те же строки
 * ещё и считаны по тарифу D1.
 *
 * Отсюда пара «функция и её SQL-двойник», как у ключа пака строкой ниже:
 * функция считает число при разборе, SQL — при дозаливке колонки в базу,
 * созданную прежней версией (см. src/db.js). Расходиться им нельзя.
 *
 * Из счёта выброшено то же самое, что не показывает и карточка:
 *
 *   всё, что не произведение, — область («Футбол», «Вторая мировая») и праздник
 *     («Новый год»): повтором они не бывают, викторина из областей и состоит,
 *     и «География ×5» о паке не говорит ничего, а «Новый год ×5» у новогоднего
 *     пака — пересказ его названия числом;
 *   предмет самого пака (доля от subjectPackShare и выше) — у пака про Гарри
 *     Поттера «Гарри Поттер ×27» не наблюдение, а пересказ названия числом.
 *
 * Доли франшиз пересекаются (одна тема бывает и про то, и про это), поэтому
 * сумма изредка переваливает за единицу. Порогам это не мешает: они спрашивают
 * «много ли», а не «сколько ровно».
 *
 * @param {Array} franchises сохранённый список повторов пака
 * @param {number} own порог subjectPackShare
 */
export function repeatShare(franchises, own) {
	return (franchises ?? [])
		.filter(item => item?.kind === 'work' && (item?.share ?? 0) < own)
		.reduce((sum, item) => sum + (item.share ?? 0), 0);
}

/**
 * SQL-двойник. Зовётся один раз — при дозаливке колонки, — и потому в нём стоит
 * имя таблицы, а не готовый псевдоним: в UPDATE псевдонима нет.
 *
 * @param {number} own порог subjectPackShare
 * @param {string} table к чьим полям обращаться
 */
export const repeatShareSql = (own, table = 'p') => `COALESCE((
	SELECT SUM(json_extract(value, '$.share'))
	FROM json_each(CASE WHEN json_valid(${table}.franchises) THEN ${table}.franchises ELSE '[]' END)
	WHERE json_extract(value, '$.kind') = 'work'
		AND json_extract(value, '$.share') < ${Number(own)}
), 0)`;

/**
 * Какая часть вопросов пака — спецвопросы. У пака без разобранных вопросов
 * ответа нет: делить не на что, и ноль тут означал бы «спецвопросов нет»,
 * а это другое.
 */
export const SPECIAL_SHARE_SQL = `CASE
	WHEN COALESCE(p.question_count, 0) > 0 AND p.special_count IS NOT NULL
	THEN p.special_count * 1.0 / p.question_count
END`;

/**
 * Какая часть показываемого в вопросах лежит не в самом паке, а по чужим
 * ссылкам (см. countMediaRefs в src/siq.js).
 *
 * NULL значит «неизвестно», и это не то же самое, что ноль: у пака, разобранного
 * до появления правила, чисел нет вовсе, а у пака без единого медиавопроса
 * делить не на что. Ни про того, ни про другого сайт не пишет ничего — а вот
 * ноль означал бы «всё на месте», и галочка «без паков на чужих ссылках»
 * пропускала бы обоих как проверенных.
 *
 * Живёт здесь, а рядом с ключом пака, по общей причине этого файла: спрашивают
 * это и дома, и наверху (см. cf/src/library/), а считаться оно обязано
 * одинаково.
 */
export const OFFSITE_SHARE_SQL = `CASE
	WHEN p.media_offsite IS NOT NULL AND COALESCE(p.media_own, 0) + p.media_offsite > 0
	THEN p.media_offsite * 1.0 / (COALESCE(p.media_own, 0) + p.media_offsite)
END`;
