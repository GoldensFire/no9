/**
 * Непристойно ли название пака.
 *
 * Считается один раз — разбором пака и пересчётом (см. recalcObscene
 * в src/indexer/recalc.js), — а не на каждый запрос страницы: два десятка
 * правил на одиннадцать тысяч названий это миллисекунды, но страница пака
 * открывается чаще, чем меняется её название.
 *
 * @param {string} name название пака (а нет его — имя файла)
 * @returns {boolean}
 */
export function isObsceneName(name) {
	const text = normalize(name);

	return text ? OBSCENE.some(rule => rule.test(text)) : false;
}
