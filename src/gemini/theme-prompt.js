/** Жанры одной тематики в строку: «isekai — исекай, mecha — меха, …». */
const genreList = topic => Object.entries(GENRES[topic].list)
	.map(([key, name]) => `${key} — ${name}`)
	.join(', ');

/**
 * Жанры всех тематик, кроме музыки и спорта: у обоих свой вопрос и своё условие.
 * Музыка спрашивается не по категории темы, а по признаку m; спорт — по виду
 * «прочего» (k=sport), потому что категорией спорт не является вовсе.
 */
const GENRE_LIST = Object.keys(GENRES)
	.filter(topic => topic !== MUSIC_KEY && topic !== SPORT_KEY)
	.map(topic => `${topic}: ${genreList(topic)}`)
	.join('\n');

/** Носители — по одному списку на тематику, у которой этот вопрос вообще стоит. */
