			// а повторяться может только произведение, — зато по a пак целиком
			// про футбол получает подпись, которой ярлык «Прочее» ему не даёт
			a: { type: 'STRING' },
			ae: { type: 'STRING' },
			// Произведения, названные в ответах темы. Массив, потому что тема-угадайка
			// называет их восемь штук подряд, и именно из них складываются повторы
			// пака (см. computeFranchises в topics.js)
			w: { type: 'ARRAY', items: { type: 'STRING' } },
			// Вид «прочего». Перечислением (enum) не ограничен нарочно: пустая строка
			// здесь законный ответ — «вида нет», — а перечисление, в котором есть
			// пустая строка, часть моделей отвергает целиком, невнятным 400 на весь
			// запрос. Проверка всё равно наша: чужое слово отсеется при разборе ответа
			k: { type: 'STRING' },
			// Праздник, к которому привязана тема. Отдельно от предмета и области
			// нарочно: праздник — это повод, а не предмет, и с предметом он
			// не спорит. Новогодняя тема про кино остаётся темой про кино,
			// и назвать её праздник было раньше негде (см. HOLIDAYS в names.js).
			// Перечислением не ограничен по той же причине, что и вид «прочего»:
			// пустая строка здесь законный ответ
			h: { type: 'STRING' },
			// Жанры темы и жанры её музыки — СПИСКОМ с числами, а не по одному
			// значению. Одно значение врало на угадайках: тема, где подряд идут
			// поп, рэп, рок и панк, отдавала весь свой вес попу, и пак выходил
			// «поп на 90%» (см. computeGenres в topics.js). Ключи перечислением
			// не ограничены по той же причине, что и вид «прочего»: списки разные
			// у каждой категории, одним enum их не выразить, а чужое слово
			// всё равно отсеется при разборе ответа
			gs: { type: 'ARRAY', items: COUNTED },
			gms: { type: 'ARRAY', items: COUNTED },
			// Носитель: манга или манхва, фильм или сериал. Устроен как жанры
