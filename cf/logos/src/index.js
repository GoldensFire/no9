// Ответ на картинку, которой ещё нет.
//
// ————— зачем здесь вообще появился код —————
//
// У этого Worker'а не было ни строчки, и в этом был весь его смысл: статику
// Cloudflare отдаёт сам, не будя код, и такие обращения не считаются запросами
// вовсе (см. cf/logos/wrangler.jsonc). Так оно и осталось: за готовой обложкой
// сюда по-прежнему никто не приходит — файл уезжает к браузеру мимо этого файла.
//
// Код нужен ровно для обратного случая — когда обложки НЕТ. Правило кэша
// Cloudflare прикладывает к адресу, а не к файлу, и ответ «такой обложки нет»
// уезжал к браузеру с тем же самым «max-age=86400», что и сама картинка
// (см. HEADERS в scripts/deploy-logos.js). А «нет» тут дело обычное: строку
// пака кладёт в D1 ежечасный обход, картинку — ближайшая выкладка, и всякий,
// кто открыл пак между ними, запоминал пустоту на сутки вперёд
// и переспрашивать больше не приходил.
//
// Видно это было так: у хозяина сайта, который заходит на новые паки в тот же
// час, обложки нет, а в чужом браузере и в окне инкогнито — есть. Разницы
// в ответах сервера при этом никакой: она вся в кэше браузера (пак 21571,
// сентябрь 2026; до того — 15915–15917 и 16554).
//
// ————— почему это ничего не стоит —————
//
// Worker просыпается только на промах: запрос, которому нашёлся файл, до кода
// не доходит. Промахи — это обложки паков, разобранных с прошлой выкладки,
// то есть единицы в день против сотен тысяч обращений за самими картинками.
//
// Node-специфичного здесь нет и быть не может: это Worker.

export default {
	/**
	 * Сюда попадает только то, чему не нашлось файла. Отвечаем тем же 404,
	 * что отвечал бы Cloudflare сам, — но с запретом запоминать ответ.
	 *
	 * no-store, а не короткий max-age: промах живёт ровно до ближайшей
	 * выкладки обложек, а когда она случится, браузеру знать неоткуда.
	 * Карточка на пустое место рисует квадрат с первой буквой названия
	 * (см. createLogo в web/common.js) — то же самое, что и раньше, только
	 * теперь до следующего захода, а не на сутки.
	 */
	fetch() {
		return new Response(null, {
			status: 404,
			headers: {
				'Cache-Control': 'no-store',
				'CDN-Cache-Control': 'no-store',
			},
		});
	},
};
